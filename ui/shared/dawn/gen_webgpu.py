"""Generate both hosts' WebGPU imports from the pinned webgpu-headers schema."""

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re

import yaml

from webgpu_idl import IDL_ENUMS, TEXTURE_FORMATS, VERTEX_FORMATS


HERE = Path(__file__).resolve().parent
BANNER = "Generated by gen_webgpu.py."
SHADER = "shader_module_descriptor"
WGSL = "shader_source_WGSL"
CHAIN = "chained_struct"
STRING = "string_view"
STRINGS = {"string_with_default_empty", "nullable_string"}

# Wasm32 scalar storage and its corresponding C type and Wasm value type.
SCALARS = {
    "bool": (4, "WGPUBool", "I32"),
    "uint16": (2, "uint16_t", "I32"),
    "uint32": (4, "uint32_t", "I32"),
    "int32": (4, "int32_t", "I32"),
    "usize": (4, "uint32_t", "I32"),
    "uint64": (8, "uint64_t", "I64"),
    "float32": (4, "float", "F32"),
    "nullable_float32": (4, "float", "F32"),
    "float64_supertype": (8, "double", "F64"),
    "address": (4, "uint32_t", "I32"),
}

# Array count names in webgpu.h normally use the singular member name.
COUNT_NAMES = {"entries": "entry"}
# The pin represents nullable pipeline-layout array elements in prose.
NULLABLE_ELEMENTS = {("pipeline_layout_descriptor", "bind_group_layouts")}
DATA_SIZES = {"wgpuQueueWriteBuffer": "size", "wgpuQueueWriteTexture": "data_size"}


def pascal(name):
    # Upstream uses a double underscore for a literal underscore in C names.
    return "_".join("".join(part[:1].upper() + part[1:] for part in word.split("_"))
                    for word in name.split("__"))


def camel(name):
    return name.split("_", 1)[0] + pascal(name.partition("_")[2])


def c_type(name):
    return "WGPU" + pascal(name)


def enum_symbol(name, entry):
    return f"{c_type(name)}_{pascal(entry)}"


def parse_imports(header):
    macro = re.search(
        r"^#define TSUGUMI_VIEW_WEBGPU_IMPORTS\(X\) \\\n((?:[^\n]*\\\n)*[^\n]*)",
        header, re.MULTILINE,
    )
    if not macro:
        raise ValueError("TSUGUMI_VIEW_WEBGPU_IMPORTS(X) was not found")
    names = []
    for line in macro[1].splitlines():
        entry = re.fullmatch(r"\s*X\([^,]+,\s*(wgpu\w+),\s*\(.*\)\)\s*\\?", line)
        if not entry:
            raise ValueError(f"invalid WebGPU import line: {line}")
        names.append(entry[1])
    if not names or len(set(names)) != len(names):
        raise ValueError("expected distinct WebGPU import names")
    return names


@dataclass(frozen=True)
class Member:
    name: str
    type: str
    pointer: bool = False
    optional: bool = False
    sentinel: str | None = None
    nullable_elements: bool = False

    @property
    def array(self):
        return self.type.startswith("array<")

    @property
    def element(self):
        return self.type[6:-1]


@dataclass(frozen=True)
class Field:
    name: str
    offset: int
    size: int
    alignment: int


@dataclass(frozen=True)
class Struct:
    name: str
    category: str
    members: tuple[Member, ...]
    fields: dict[str, Field]
    size: int
    alignment: int


@dataclass(frozen=True)
class Function:
    name: str
    receiver: str
    method: str
    args: tuple[Member, ...]
    result: str | None
    release: bool = False


def align(offset, alignment):
    return (offset + alignment - 1) // alignment * alignment


def layout(name, category, members, storage):
    fields = {}
    end = 0
    alignment = 1
    for field, (size, field_alignment) in storage:
        offset = align(end, field_alignment)
        fields[field] = Field(field, offset, size, field_alignment)
        end = offset + size
        alignment = max(alignment, field_alignment)
    return Struct(name, category, tuple(members), fields, align(end, alignment), alignment)


def count_name(member):
    return COUNT_NAMES.get(member.name, member.name.removesuffix("s")) + "_count"


def named(entries):
    return {item["name"]: item for item in entries}


class Model:
    def __init__(self, schema, names):
        self.objects = named(schema["objects"])
        self.struct_defs = named(schema["structs"])
        self.enum_defs = named(schema["enums"])
        self.flag_defs = named(schema["bitflags"])
        self.constants = {item["name"]: item["value"] for item in schema["constants"]}
        self.enum_prefix = schema["enum_prefix"]
        self.structs = {}
        self.enums = {}
        self.flags = {}
        self.kinds = set()
        self._building = set()
        methods = {}
        for receiver, obj in self.objects.items():
            prefix = "wgpu" + pascal(receiver)
            methods[prefix + "Release"] = (receiver, {"name": "release"}, True)
            for method in obj.get("methods", ()):
                methods[prefix + pascal(method["name"])] = (receiver, method, False)
        self.functions = [self.make_function(name, methods.get(name)) for name in names]

    def make_function(self, name, definition):
        if definition is None:
            raise ValueError(f"{name}: expected an object method")
        receiver, method, release = definition
        if "callback" in method or method["name"] == "add_ref":
            raise ValueError(f"{name}: callbacks and AddRef are unsupported")
        if release and receiver in {"device", "queue"}:
            raise ValueError(f"{name}: the host owns this handle")
        result = method.get("returns")
        if result is not None and (
            not result["type"].startswith("object.") or not result.get("passed_with_ownership")
            or result.get("pointer")
        ):
            raise ValueError(f"{name}: expected an owned object return")
        args = [self.member(name, arg) for arg in method.get("args", ())]
        if any((arg.type.startswith("struct.") and not arg.pointer) or arg.type in STRINGS
               for arg in args):
            raise ValueError(f"{name}: by-value aggregate argument")
        if any(arg.type == "c_void_data_ptr" for arg in args):
            expected_size = DATA_SIZES.get(name)
            if not any(arg.name == expected_size and arg.type == "usize" and not arg.pointer
                       for arg in args):
                raise ValueError(f"{name}: unbounded data pointer")
        self.kinds.add(receiver)
        if result:
            self.measure(result["type"])
        return Function(name, receiver, method["name"], tuple(args),
                        result["type"].split(".")[1] if result else None, release)

    def member(self, owner, node):
        name, type_name = node["name"], node["type"]
        pointer = node.get("pointer")
        optional = node.get("optional", False)
        default = node.get("default")
        sentinel = default.split(".")[1] if isinstance(default, str) and default.startswith("constant.") else None
        array = re.fullmatch(r"array<([^<>]+)>", type_name)
        if pointer not in {None, "immutable"}:
            raise ValueError(f"{owner}.{name}: writable or unsupported pointer")
        if array:
            if pointer is None or optional:
                raise ValueError(f"{owner}.{name}: unsupported array representation")
            self.measure(array[1])
        elif pointer:
            if type_name.startswith("struct."):
                self.measure(type_name)
            elif type_name != "c_void_data_ptr" or owner not in DATA_SIZES or name != "data" or optional:
                raise ValueError(f"{owner}.{name}: unsupported pointer to {type_name}")
        else:
            self.measure(type_name)
            if optional and not type_name.startswith("object."):
                raise ValueError(f"{owner}.{name}: unsupported optional {type_name}")
        if sentinel is not None:
            self.constant(sentinel)
        return Member(name, type_name, pointer is not None, optional, sentinel,
                      (owner, name) in NULLABLE_ELEMENTS)

    def constant(self, name):
        value = self.constants[name]
        return {"uint32_max": 2**32 - 1, "usize_max": 2**32 - 1,
                "uint64_max": 2**64 - 1, "nan": None}[value]

    def measure(self, type_name):
        if type_name in SCALARS:
            size, _, _ = SCALARS[type_name]
            return size, size
        if type_name in STRINGS:
            self.builtin_struct(STRING, ("data", "length"))
            return 8, 4
        category, _, name = type_name.partition(".")
        if category == "object" and name in self.objects:
            self.kinds.add(name)
            return 4, 4
        if category == "enum" and name in self.enum_defs:
            if name not in self.enums:
                self.enums[name] = {
                    entry["name"]: self.enum_prefix << 16 | index
                    for index, entry in enumerate(self.enum_defs[name]["entries"]) if entry
                }
            return 4, 4
        if category == "bitflag" and name in self.flag_defs:
            if name not in self.flags:
                self.flags[name] = self.flag_values(name)
            return 8, 8
        if category == "struct" and name in self.struct_defs:
            struct = self.build_struct(name)
            return struct.size, struct.alignment
        raise ValueError(f"unsupported ABI type {type_name}")

    def flag_values(self, name):
        values = {}
        bit = 1
        for entry in self.flag_defs[name]["entries"]:
            key = entry["name"]
            if key == "none":
                value = 0
            elif "value_combination" in entry:
                value = 0
                for flag in entry["value_combination"]:
                    value |= values[flag]
            else:
                value = bit
                bit <<= 1
            values[key] = value
        return values

    def builtin_struct(self, name, fields):
        if name not in self.structs:
            self.structs[name] = layout(name, "builtin", (), [(field, (4, 4)) for field in fields])
        return self.structs[name]

    def build_struct(self, name):
        if name in self.structs:
            return self.structs[name]
        if name in self._building:
            raise ValueError(f"{name}: recursive structures are unsupported")
        self._building.add(name)
        definition = self.struct_defs[name]
        category = definition["type"]
        if definition.get("free_members") or category not in {"standalone", "extensible", "extension"}:
            raise ValueError(f"{name}: unsupported struct category or ownership")
        storage = []
        if category == "extensible":
            storage.append(("next_in_chain", (4, 4)))
        if category == "extension":
            if name != WGSL or definition["extends"] != [SHADER]:
                raise ValueError(f"{name}: unexpected extension")
            self.builtin_struct(CHAIN, ("next", "s_type"))
            self.measure("enum.s_type")
            storage.append(("chain", (8, 4)))
        if name == SHADER:
            self.build_struct(WGSL)
        members = [self.member(name, node) for node in definition["members"]]
        for member in members:
            if member.array:
                storage.append((count_name(member), (4, 4)))
            size_align = (4, 4) if member.pointer else self.measure(member.type)
            storage.append((member.name, size_align))
        struct = layout(name, category, members, storage)
        self.structs[name] = struct
        self._building.remove(name)
        return struct


def load_model(yml, header):
    return Model(yaml.safe_load(yml.read_text()), parse_imports(header.read_text()))


def value_args(fn):
    """Expand C array arguments into their count and pointer Wasm arguments."""
    for member in fn.args:
        if member.array:
            yield count_name(member), "usize"
        yield member.name, "address" if member.pointer else member.type


def val_type(type_name):
    if type_name in SCALARS:
        return SCALARS[type_name][2]
    if type_name.startswith("bitflag."):
        return "I64"
    return "I32"


def layout_check(model):
    lines = [
        f"/* {BANNER} */",
        "#include <stddef.h>",
        "#include <tsugumi/tsugumi_view.h>",
        "",
    ]

    def check(expr, value):
        lines.append(f'_Static_assert({expr} == {value}, "{expr}");')

    for c_name, size in (("void *", 4), ("size_t", 4), ("WGPUBool", 4), ("WGPUFlags", 8)):
        check(f"sizeof({c_name})", size)
        check(f"_Alignof({c_name})", size)
    for struct in model.structs.values():
        c_name = c_type(struct.name)
        lines.append("")
        check(f"sizeof({c_name})", struct.size)
        check(f"_Alignof({c_name})", struct.alignment)
        for field in struct.fields.values():
            check(f"offsetof({c_name}, {camel(field.name)})", field.offset)
    for groups, size in ((model.enums, 4), (model.flags, 8)):
        for name, values in groups.items():
            lines.append("")
            check(f"sizeof({c_type(name)})", size)
            check(f"_Alignof({c_type(name)})", size)
            for entry, value in values.items():
                check(enum_symbol(name, entry), hex(value))
    sentinels = {"strlen"} | {
        member.sentinel for struct in model.structs.values() for member in struct.members
        if member.sentinel is not None
    }
    if any(fn.name in WHOLE_SIZE_FUNCTIONS for fn in model.functions):
        sentinels.add("whole_size")
    lines.append("")
    for sentinel in sorted(sentinels):
        value = model.constant(sentinel)
        if value is None:
            lines.append(f'_Static_assert(__builtin_isnan(WGPU_{sentinel.upper()}), "{sentinel}");')
        else:
            check(f"WGPU_{sentinel.upper()}", f"{hex(value)}ULL")
    return "\n".join(lines) + "\n"


WHOLE_SIZE_FUNCTIONS = {"wgpuRenderPassEncoderSetIndexBuffer", "wgpuRenderPassEncoderSetVertexBuffer"}


def cpp_type(type_name):
    if type_name in SCALARS:
        return SCALARS[type_name][1]
    if type_name in STRINGS:
        return "WGPUStringView"
    return c_type(type_name.split(".")[1])


def cpp_enum(name, values):
    lines = [f"auto convert_{pascal(name)}(const Reader& reader, uint32_t value,",
             f"    std::string_view field) -> {c_type(name)} {{",
             "  switch (value) {"]
    lines.extend(f"    case {hex(value)}: return {enum_symbol(name, entry)};"
                 for entry, value in values.items())
    lines += ["  }", f'  reader.fail(field, "unknown {c_type(name)} value " + std::to_string(value));', "}"]
    return lines


def cpp_flags(name, values):
    mask = 0
    for value in values.values():
        mask |= value
    return [
        f"auto convert_{pascal(name)}(const Reader& reader, uint64_t value,",
        f"    std::string_view field) -> {c_type(name)} {{",
        f'  if (value & ~{hex(mask)}ULL) reader.fail(field, "unknown {c_type(name)} bits");',
        f"  {c_type(name)} result = 0;",
        *(f"  if (value & {hex(value)}ULL) result |= {enum_symbol(name, entry)};"
          for entry, value in values.items() if value and value.bit_count() == 1),
        "  return result;",
        "}",
    ]


def cpp_value(type_name, value, field, optional=False, take=False):
    category, _, name = type_name.partition(".")
    if category in {"enum", "bitflag"}:
        return f"convert_{pascal(name)}(reader, {value}, {field})"
    if category == "object":
        method = "take" if take else "handle"
        nullable = "" if take else f", {str(optional).lower()}"
        return f"reader.{method}<{c_type(name)}>(Kind::{pascal(name)}, {value}{nullable}, {field})"
    return value


def cpp_read(type_name, address, field, optional=False):
    category, _, name = type_name.partition(".")
    if category == "struct":
        return f"read_{pascal(name)}(reader, arena, {address}, {field})"
    if type_name in STRINGS:
        return f"read_StringView(reader, arena, {address}, {field})"
    storage = ("uint64_t" if category == "bitflag" else "uint32_t"
               if category in {"object", "enum"} else cpp_type(type_name))
    return cpp_value(type_name, f"reader.read<{storage}>({address}, {field})", field, optional)


def cpp_array(model, member, address, count, field):
    stride, _ = model.measure(member.element)
    decode = cpp_read(member.element, "element", field, member.nullable_elements)
    return (f"reader.array<{cpp_type(member.element)}>(arena, {address}, {count}, {stride}, {field},\n"
            f"      [&](uint64_t element) {{ return {decode}; }})")


def cpp_pointer(member, address, field):
    name = pascal(member.type.split(".")[1])
    method = f"read_{name}(reader, arena, {address}, {field})"
    return f"copy_{'optional' if member.optional else 'required'}(arena, {address}, [&] {{ return {method}; }})"


def cpp_decode(model, struct):
    name = pascal(struct.name)
    c_name = c_type(struct.name)
    lines = [f"auto read_{name}(const Reader& reader, [[maybe_unused]] Arena& arena,",
             f"    uint64_t ptr, std::string_view field) -> {c_name} {{",
             f"  if (ptr == 0) reader.fail(field, \"null pointer\");",
             f"  reader.range(ptr, {struct.size}, field);"]

    def address(name):
        return f"ptr + {struct.fields[name].offset}"

    def read_u32(key, field):
        return f"reader.read<uint32_t>({address(key)}, {field})"

    if struct.name == STRING:
        lines.append(f"  return reader.string(arena, {read_u32('data', 'field')}, {read_u32('length', 'field')}, field);")
    elif struct.name == CHAIN:
        chain_value = model.enums["s_type"][WGSL]
        lines.extend([
            f"  if ({read_u32('s_type', 'field')} != {hex(chain_value)}) reader.fail(field, \"expected WGPUShaderSourceWGSL\");",
            f"  if ({read_u32('next', 'field')} != 0) reader.fail(field, \"unexpected chained extension\");",
            "  return {nullptr, WGPUSType_ShaderSourceWGSL};",
        ])
    else:
        lines.append(f"  {c_name} result{{}};")
        if struct.category == "extensible":
            field = f'"{c_name}.nextInChain"'
            lines.append(f"  const auto chain = {read_u32('next_in_chain', field)};")
            if struct.name == SHADER:
                lines += [
                    "  if (chain != 0) {",
                    "    auto* source = arena.allocate<WGPUShaderSourceWGSL>();",
                    f"    *source = read_ShaderSourceWGSL(reader, arena, chain, {field});",
                    "    result.nextInChain = &source->chain;",
                    "  }",
                ]
            else:
                lines.append(f'  if (chain != 0) reader.fail({field}, "unexpected chained extension");')
        if struct.category == "extension":
            lines.append(f"  result.chain = read_ChainedStruct(reader, arena, {address('chain')}, field);")
        for member in struct.members:
            key = camel(member.name)
            field = f'"{c_name}.{key}"'
            if member.array:
                count = count_name(member)
                count_out = f"result.{camel(count)}"
                lines.append(f"  {count_out} = {read_u32(count, field)};")
                expr = cpp_array(model, member, read_u32(member.name, field), count_out, field)
            elif member.pointer:
                local = f"{key}Address"
                lines.append(f"  const auto {local} = {read_u32(member.name, field)};")
                expr = cpp_pointer(member, local, field)
            else:
                expr = cpp_read(member.type, address(member.name), field, member.optional)
            lines.append(f"  result.{key} = {expr};")
        lines.append("  return result;")
    return lines + ["}"]


def cpp_call(model, fn):
    lines = [
        f"auto call_{fn.name}(Context& context, const Val* args, [[maybe_unused]] Val* results) -> void {{",
        f'  Reader reader(context, "{fn.name}");',
    ]
    proc = f"context.procs.{fn.name}"
    lines.append(f'  if ({proc} == nullptr) reader.fail("proc", "missing procedure");')
    if any(member.pointer for member in fn.args):
        lines.append("  Arena arena;")
    for index, (name, type_name) in enumerate(value_args(fn), 1):
        kind = val_type(type_name)
        expr = f"args[{index}].{kind.lower()}"
        scalar = "uint64_t" if kind == "I64" else (
            "uint32_t" if kind == "I32" and type_name != "int32" else None
        )
        if scalar:
            expr = f"static_cast<{scalar}>({expr})"
        lines.append(f"  const auto raw_{name} = {expr};")
    call_args = ["receiver"]
    for member in fn.args:
        name = member.name
        field = f'"{camel(name)}"'
        raw = f"raw_{name}"
        if member.array:
            count = f"raw_{count_name(member)}"
            expr = cpp_array(model, member, raw, count, field)
            call_args.append(count)
        elif member.type == "c_void_data_ptr":
            expr = f"reader.data({raw}, raw_{DATA_SIZES[fn.name]}, {field})"
        elif member.pointer:
            expr = cpp_pointer(member, raw, field)
        else:
            expr = cpp_value(member.type, raw, field, member.optional)
        lines.append(f"  const auto arg_{name} = {expr};")
        call_args.append(f"arg_{name}")
    receiver = cpp_value(f"object.{fn.receiver}", "static_cast<uint32_t>(args[0].i32)",
                         f'"{camel(fn.receiver)}"', take=fn.release)
    lines.append(f"  const auto receiver = {receiver};")
    call = f"{proc}({', '.join(call_args)})"
    if fn.result:
        lines.append(f"  auto native = {call};")
        lines.append(f"  results[0].i32 = std::bit_cast<int32_t>(context.handles.add(Kind::{pascal(fn.result)}, native));")
    else:
        lines.append(f"  {call};")
    return lines + ["}"]


def cpp_outputs(model):
    header = [
        f"// {BANNER}", "#pragma once", "", "#include <span>", "#include <webgpu/webgpu.h>",
        '#include "gen_support.h"', "", "namespace tsugumi::view {", "", "struct Procs {",
    ]
    header += [f"  WGPUProc{fn.name[4:]} {fn.name} = nullptr;" for fn in model.functions]
    header += [
        "};", "", "auto dawnProcs() -> Procs;", "",
        "struct Context {", "  Memory memory;", "  Handles& handles;", "  const Procs& procs;", "};", "",
        "struct Import {", "  const char* name;", "  std::span<const ValType> params;",
        "  std::span<const ValType> results;", "  void (*call)(Context&, const Val*, Val*);", "};",
        "", "auto imports() -> std::span<const Import>;", "",
    ]

    cc = [f"// {BANNER}", '#include "webgpu_imports.gen.h"', "",
          (HERE / "cpp_reader.inc").read_text().rstrip(), ""]
    if any(member.pointer and not member.array and member.type.startswith("struct.")
           for struct in model.structs.values() for member in struct.members) or any(
        member.pointer and not member.array and member.type.startswith("struct.")
        for fn in model.functions for member in fn.args
    ):
        cc += [
            "template <class Decode>",
            "auto copy_required(Arena& arena, uint32_t, Decode decode) {",
            "  auto value = decode();",
            "  auto* storage = arena.allocate<decltype(value)>();",
            "  *storage = value;",
            "  return storage;",
            "}", "",
            "template <class Decode>",
            "auto copy_optional(Arena& arena, uint32_t address, Decode decode) -> decltype(copy_required(arena, address, decode)) {",
            "  if (address == 0) return nullptr;",
            "  return copy_required(arena, address, decode);",
            "}", "",
        ]
    for name, values in model.enums.items():
        if name != "s_type":
            cc += cpp_enum(name, values) + [""]
    for name, values in model.flags.items():
        cc += cpp_flags(name, values) + [""]
    for struct in model.structs.values():
        cc += cpp_decode(model, struct) + [""]
    for fn in model.functions:
        cc += cpp_call(model, fn) + [""]
    signatures = {}
    for fn in model.functions:
        params = ("I32", *(val_type(t) for _, t in value_args(fn)))
        if params not in signatures:
            key = "k" + "_".join(params)
            values = ", ".join(f"ValType::{p}" for p in params)
            cc.append(f"constexpr ValType {key}[] = {{{values}}};")
            signatures[params] = key
    cc += ["", "constexpr Import kImports[] = {"]
    for fn in model.functions:
        params = ("I32", *(val_type(t) for _, t in value_args(fn)))
        result = "kI32" if fn.result else "{}"
        cc.append(f'    {{"{fn.name}", {signatures[params]}, {result}, call_{fn.name}}},')
    cc += ["};", "", "}  // namespace", "", "auto imports() -> std::span<const Import> { return kImports; }"]
    for struct in model.structs.values():
        name = pascal(struct.name)
        c_name = c_type(struct.name)
        signature = f"auto decode_{name}(Context& context, Arena& arena, uint32_t ptr) -> {c_name}"
        header.append(f"{signature};")
        cc += ["", f"{signature} {{", f'  Reader reader(context, "decode_{name}");',
               f'  return read_{name}(reader, arena, ptr, "{c_name}");', "}"]
    dawn = [
        f"// {BANNER}", '#include "webgpu_imports.gen.h"', "", "namespace tsugumi::view {", "",
        "auto dawnProcs() -> Procs {", "  return {",
        *(f"      .{fn.name} = &{fn.name}," for fn in model.functions),
        "  };", "}",
    ]
    return {name: "\n".join(lines + ["", "}  // namespace tsugumi::view", ""])
            for name, lines in [
                ("webgpu_imports.gen.h", header), ("webgpu_imports.gen.cc", cc),
                ("webgpu_procs_dawn.gen.cc", dawn),
            ]}


def js_enum(name, entry):
    if entry == "undefined":
        return "undefined"
    if name == "optional_bool" and entry in {"true", "false"}:
        return entry
    if entry == "binding_not_used" and name in {
        "buffer_binding_type", "sampler_binding_type", "texture_sample_type", "storage_texture_access"
    }:
        return "NOT_USED"
    value = entry.lower().replace("_", "-")
    if name == "texture_format":
        value = TEXTURE_FORMATS.get(entry.lower().replace("_", ""))
    if name == "vertex_format":
        value = VERTEX_FORMATS.get(entry, value)
    if value not in IDL_ENUMS.get(name, "").split():
        raise ValueError(f"{name}.{entry}: missing WebGPU IDL spelling")
    return json.dumps(value)


def js_value(type_name, value, field, optional=False, sentinel=None, preserve_null=False):
    category, _, name = type_name.partition(".")
    if category == "object":
        expr = f"reader.handle('{pascal(name)}', {value}, {str(optional).lower()}, {field})"
        return f"{expr} ?? undefined" if optional and not preserve_null else expr
    if category == "enum":
        return f"reader.enum({pascal(name)}, {value}, {field})"
    if category == "bitflag":
        return f"reader.flags({pascal(name)}Mask, {value}, {field})"
    if type_name == "bool":
        return f"{value} !== 0"
    if type_name == "uint64":
        expr = f"reader.number({value}, {field})"
        return f"{value} === {sentinel} ? undefined : {expr}" if sentinel else expr
    if type_name == "nullable_float32":
        return f"Number.isNaN({value}) ? undefined : {value}"
    return f"{value} === {sentinel} ? undefined : {value}" if sentinel else value


JS_READ = {
    "bool": "u32", "uint16": "u16", "uint32": "u32", "int32": "i32", "usize": "u32",
    "uint64": "u64", "float32": "f32", "nullable_float32": "f32", "float64_supertype": "f64",
}


def js_read(type_name, address, field):
    category, _, name = type_name.partition(".")
    if type_name in STRINGS:
        return f"read_StringView(reader, {address}, {field})"
    if category == "struct":
        return f"read_{pascal(name)}(reader, {address}, {field})"
    method = ("u32" if category in {"object", "enum"} else
              "u64" if category == "bitflag" else JS_READ[type_name])
    return f"reader.{method}({address}, {field})"


def js_array(model, member, address, count, field):
    stride, _ = model.measure(member.element)
    raw = js_read(member.element, "element", field)
    decode = js_value(member.element, raw, field, member.nullable_elements, preserve_null=True)
    return f"reader.array({address}, {count}, {stride}, {field}, element => {decode})"


# C encodes several nullable sequence elements as fields on a present struct.
JS_HOLES = {
    "color_target_state": "format === undefined",
    "render_pass_color_attachment": "view === undefined",
    "vertex_buffer_layout": "stepMode === undefined && attributes.length === 0",
}
LAYOUT_FIELDS = {
    "buffer_binding_layout": "type",
    "sampler_binding_layout": "type",
    "storage_texture_binding_layout": "access",
    "texture_binding_layout": "sampleType",
}


def js_decode(model, struct):
    name = pascal(struct.name)
    lines = [f"function read_{name}(reader, ptr, field) {{",
             f"  reader.required(ptr, {struct.size}, field)"]

    def address(key):
        return f"ptr + {struct.fields[key].offset}"

    def read_u32(key, field):
        return f"reader.u32({address(key)}, {field})"

    if struct.name == STRING:
        lines.append(f"  return reader.string({read_u32('data', 'field')}, {read_u32('length', 'field')}, field)")
        return lines + ["}"]
    if struct.name == CHAIN:
        return lines + [
            f"  if ({read_u32('s_type', 'field')} !== {model.enums['s_type'][WGSL]}) "
            "reader.fail(field, 'expected WGPUShaderSourceWGSL')",
            f"  if ({read_u32('next', 'field')} !== 0) reader.fail(field, 'unexpected chained extension')",
            "}",
        ]

    output = []
    if struct.category == "extensible":
        chain_field = f"'{c_type(struct.name)}.nextInChain'"
        lines.append(f"  const chain = {read_u32('next_in_chain', chain_field)}")
        if struct.name == SHADER:
            lines += [
                f"  if (chain === 0) reader.fail({chain_field}, 'missing WGPUShaderSourceWGSL')",
                f"  const {{ code }} = read_ShaderSourceWGSL(reader, chain, {chain_field})",
            ]
            output.append("code: code ?? ''")
        else:
            lines.append(f"  if (chain !== 0) reader.fail({chain_field}, 'unexpected chained extension')")
    if struct.category == "extension":
        lines.append(f"  read_ChainedStruct(reader, {address('chain')}, field)")
    for member in struct.members:
        key = camel(member.name)
        local = f"member_{key}"  # Some WebGPU member names are reserved words.
        field = f"'{c_type(struct.name)}.{key}'"
        if member.array:
            count = read_u32(count_name(member), field)
            expr = js_array(model, member, read_u32(member.name, field), count, field)
        elif member.pointer:
            lines.append(f"  const {local}Address = {read_u32(member.name, field)}")
            expr = js_read(member.type, f"{local}Address", field)
            if member.optional:
                expr = f"{local}Address === 0 ? undefined : {expr}"
        else:
            expr = js_read(member.type, address(member.name), field)
            sentinel = None
            if member.sentinel is not None and member.type != "nullable_float32":
                value = model.constant(member.sentinel)
                sentinel = f"{hex(value)}{'n' if member.type == 'uint64' else ''}"
            if sentinel is not None or member.type == "nullable_float32":
                lines.append(f"  const {local}Raw = {expr}")
                expr = f"{local}Raw"
            expr = js_value(member.type, expr, field, member.optional, sentinel)
        lines.append(f"  const {local} = {expr}")
        if struct.name == "bind_group_entry" and key != "binding":
            continue
        if struct.name == "bind_group_layout_entry" and key == "bindingArraySize":
            lines.append(f"  if ({local} !== 0) reader.fail({field}, 'binding arrays are unavailable in WebGPU IDL')")
            continue
        if key == "constants" and member.element == "struct.constant_entry":
            output.append(f"constants: Object.fromEntries({local}.map(({{ key, value }}) => [key, value]))")
        elif key == "layout" and member.type == "object.pipeline_layout":
            output.append(f"layout: {local} ?? 'auto'")
        elif struct.name == "constant_entry" and key == "key":
            output.append(f"key: {local} ?? ''")
        else:
            output.append(f"{key}: {local}")
    if struct.name in LAYOUT_FIELDS:
        lines.append(f"  if (member_{LAYOUT_FIELDS[struct.name]} === NOT_USED) return undefined")
    if struct.name in JS_HOLES:
        condition = re.sub(r"\b(format|view|stepMode|attributes)\b",
                           r"member_\1", JS_HOLES[struct.name])
        lines.append(f"  if ({condition}) return null")
    if struct.name == "bind_group_entry":
        lines += [
            "  const resources = [member_buffer, member_sampler, member_textureView]",
            "  if (resources.filter(resource => resource !== undefined).length !== 1) {",
            "    reader.fail('WGPUBindGroupEntry.resource', 'expected exactly one binding resource')",
            "  }",
            "  const resource = member_buffer === undefined ? member_sampler ?? member_textureView : {",
            "    buffer: member_buffer, offset: member_offset, size: member_size,",
            "  }",
        ]
        output.append("resource")
    lines.append(f"  return {{ {', '.join(output)} }}")
    return lines + ["}"]


def js_call(model, fn):
    args = list(value_args(fn))
    signature = ", ".join(["id", *(f"raw_{name}" for name, _ in args)])
    lines = [
        f"    {fn.name}({signature}) {{",
        f"      const reader = new Reader(ctx, '{fn.name}')",
    ]
    kind = pascal(fn.receiver)
    if fn.release:
        return lines + [f"      reader.take('{kind}', id >>> 0, '{camel(fn.receiver)}')", "    },"]
    for name, type_name in args:
        if val_type(type_name) == "I32" and type_name != "int32":
            lines.append(f"      raw_{name} >>>= 0")
        if val_type(type_name) == "I64":
            lines.append(f"      raw_{name} = BigInt.asUintN(64, raw_{name})")
    for member in fn.args:
        name = member.name
        raw = f"raw_{name}"
        field = f"'{camel(name)}'"
        if member.array:
            expr = js_array(model, member, raw, f"raw_{count_name(member)}", field)
        elif member.type == "c_void_data_ptr":
            expr = f"reader.data({raw}, raw_{DATA_SIZES[fn.name]}, {field})"
        elif member.pointer:
            expr = js_read(member.type, raw, field)
            if member.optional:
                expr = f"{raw} === 0 ? undefined : {expr}"
        else:
            sentinel = "U64_MAX" if fn.name in WHOLE_SIZE_FUNCTIONS and name == "size" else None
            expr = js_value(member.type, raw, field, member.optional, sentinel, preserve_null=True)
            if member.type.startswith("enum."):
                lines.append(f"      const arg_{name} = {expr}")
                lines.append(f"      if (arg_{name} === undefined) reader.fail({field}, 'required enum value')")
                continue
        lines.append(f"      const arg_{name} = {expr}")
    call_args = [f"arg_{member.name}" for member in fn.args if member.name != DATA_SIZES.get(fn.name)]
    lines.append(f"      const receiver = reader.handle('{kind}', id >>> 0, false, '{camel(fn.receiver)}')")
    call = f"receiver.{camel(fn.method)}({', '.join(call_args)})"
    if fn.result:
        lines.append(f"      return ctx.handles.add('{pascal(fn.result)}', {call}) | 0")
    else:
        lines.append(f"      {call}")
    return lines + ["    },"]


def js_outputs(model):
    lines = [f"// {BANNER}", (HERE / "js_reader.inc").read_text().rstrip(), ""]
    for name, values in model.enums.items():
        if name == "s_type":
            continue
        lines += [f"const {pascal(name)} = {{",
                  *(f"  {value}: {js_enum(name, entry)}," for entry, value in values.items()),
                  "}", ""]
    for name, values in model.flags.items():
        mask = 0
        for value in values.values():
            mask |= value
        lines.append(f"const {pascal(name)}Mask = {hex(mask)}n")
    lines.append("")
    for struct in model.structs.values():
        lines += js_decode(model, struct) + [""]
    lines += ["export const importNames = Object.freeze([",
              *(f"  '{fn.name}'," for fn in model.functions), "])", ""]
    if "texture_format" in model.enums:
        lines += ["export const textureFormatValue = new Map([",
                  *(f"  [{js_enum('texture_format', entry)}, {value}],"
                    for entry, value in model.enums["texture_format"].items() if entry != "undefined"),
                  "])", ""]
    else:
        lines += ["export const textureFormatValue = new Map()", ""]
    lines += ["export function webgpuImports(ctx) {", "  return {"]
    for fn in model.functions:
        lines += js_call(model, fn)
    lines += ["  }", "}", ""]

    declarations = [
        f"// {BANNER}",
        "export class TrapError extends Error {}",
        "export class Handles {",
        "  add(kind: string, object: object | null | undefined): number",
        "  get<T extends object = object>(kind: string, id: number): T",
        "  take<T extends object = object>(kind: string, id: number): T",
        "  takeIfPresent<T extends object = object>(kind: string, id: number): T | undefined",
        "}",
        "export const textureFormatValue: Map<string, number>",
        "export const importNames: readonly string[]",
        "export type WebGPUImports = {",
    ]
    for fn in model.functions:
        params = ["id: number"]
        params += [f"{camel(name)}: {'bigint' if val_type(type_name) == 'I64' else 'number'}"
                   for name, type_name in value_args(fn)]
        declarations.append(f"  {fn.name}({', '.join(params)}): {'number' if fn.result else 'void'}")
    declarations += [
        "}",
        "export function webgpuImports(ctx: { memory: () => ArrayBuffer; handles: Handles }): WebGPUImports",
        "",
    ]
    return "\n".join(lines), "\n".join(declarations)


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--webgpu-yml", type=Path, required=True)
    parser.add_argument("--view-header", type=Path, required=True)
    parser.add_argument("--cpp", type=Path)
    parser.add_argument("--js", type=Path)
    parser.add_argument("--layout-check", type=Path)
    args = parser.parse_args()
    if not any((args.cpp, args.js, args.layout_check)):
        parser.error("choose an output with --cpp, --js or --layout-check")
    try:
        model = load_model(args.webgpu_yml, args.view_header)
        # A schema change must be supported by both hosts before either builds.
        for name, entries in model.enums.items():
            if name != "s_type":
                for entry in entries:
                    js_enum(name, entry)
        if args.cpp:
            for name, content in cpp_outputs(model).items():
                write(args.cpp / name, content)
        if args.js:
            source, declarations = js_outputs(model)
            write(args.js, source)
            write(args.js.with_suffix(".d.ts"), declarations)
        if args.layout_check:
            write(args.layout_check, layout_check(model))
    except (ValueError, KeyError, OSError, yaml.YAMLError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
