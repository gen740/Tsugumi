"""Writes docs/Protocol.md from protocol/tsugumi.fbs: every request of
RequestPayload with its doc comment and fields, then the notifications. The
schema stays the single source; run this after changing it
(tests/python/test_docs.py checks that it was). --check only compares."""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FBS = ROOT / "protocol" / "tsugumi.fbs"
OUT = ROOT / "docs" / "Protocol.md"

GROUPS = [
    ("接続", ["SessionHello"]),
    ("プロジェクトと保存", ["ProjectOpen", "ProjectClose", "ProjectInspect", "ProjectSave", "ProjectReload",
                       "ProjectValidate", "ProjectImport", "ProjectCacheClear", "OperationGet"]),
    ("ファイル", ["ProjectFileList", "ProjectFileStat", "ProjectFileRead", "ProjectFileFormat", "AttachedFolderRead"]),
    ("Card の SDK と型", ["CardSDKPrepare", "CardSDKStatus", "OutputTypes"]),
    ("実行", ["RunPlan", "Run", "RunCancel", "RunStatus"]),
    ("履歴と成果物", ["RunHistory", "RunInvocations", "RunRecord", "RunValueRead", "RunHistoryDelete",
                 "ArtifactList", "ArtifactRead", "LogRange"]),
    ("表示", ["ViewSetVisible", "ViewSave"]),
    ("版", ["VersionInit", "VersionMark", "VersionCheckout", "VersionGraph", "VersionCanvas", "VersionDiff", "VersionSummary"]),
]


def union_members(text: str, name: str) -> list[str]:
    found = re.search(rf"^union {name} \{{(.*?)^\}}", text, re.S | re.M)
    assert found, name
    return re.findall(r"^\s*(?:\w+\s*:\s*[\w.]+|(\w+))\s*=\s*\d+", found.group(1), re.M)


def tables(text: str) -> dict[str, dict]:
    """Each table with its /// comment and fields (name, type, required, comment)."""
    out: dict[str, dict] = {}
    comment: list[str] = []
    current = None
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("///"):
            comment.append(line[3:].strip())
            continue
        if current is None:
            one = re.match(r"table (\w+) \{(.*)\}\s*$", line)
            many = re.match(r"table (\w+) \{\s*$", line)
            if one:
                body = one.group(2).strip()
                out[one.group(1)] = {"doc": " ".join(comment), "fields": fields_of(body)}
            elif many:
                current = many.group(1)
                out[current] = {"doc": " ".join(comment), "fields": []}
            comment = []
        elif line == "}":
            current = None
            comment = []
        else:
            for f in fields_of(line):
                f["doc"] = " ".join(comment)
                out[current]["fields"].append(f)
            if line:
                comment = []
    return out


def fields_of(body: str) -> list[dict]:
    found = []
    for m in re.finditer(r"(\w+)\s*:\s*(\[?[\w.]+\]?)\s*(=\s*[^;(]+)?\s*(\([^)]*\))?\s*;", body):
        attrs = m.group(4) or ""
        found.append({"name": m.group(1), "type": m.group(2).replace("Tsugumi.Data.", ""),
                      "required": "required" in attrs, "doc": ""})
    return found


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    text = FBS.read_text()
    all_tables = tables(text)
    requests = [m[: -len("Request")] for m in union_members(text, "RequestPayload")]
    grouped = [n for _, names in GROUPS for n in names]
    assert sorted(grouped) == sorted(requests), set(grouped) ^ set(requests)

    out = [
        "# RPC 契約",
        "",
        "<!-- Generated by protocol/generate_docs.py from protocol/tsugumi.fbs: do not edit. -->",
        "",
        "UI・Web・Agent が `tsugumid` と話す RPC の一覧です。[protocol/tsugumi.fbs](../protocol/tsugumi.fbs) の doc comment から生成しているので、説明は英語のままです。",
        "",
        "- **形式**: 1 メッセージが 1 つの FlatBuffer（root は `Tsugumi.RPC.Message`、file identifier は `TSG1`）。WebSocket の subprotocol は `tsugumi.rpc.v1`、Unix ソケットは 4 byte の長さ（little endian）に続けて本体です。",
        "- **失敗**: どの要求にも `Failure` で答えることがあります。",
        "- **変更を伴う要求**: `op_id` を持ち、同じ `op_id` の再送は 1 回だけ適用されます。応答を失ったら `OperationGet` で確かめます。",
        "- **Agent の tool**: 同じスキーマ（`tsugumi.bfbs`）から作ります（[主要機能](features.md#9-agent)）。",
        "",
        f"要求は {len(requests)} 種あります。",
        "",
    ]
    for title, names in GROUPS:
        out += [f"## {title}", "", "| 要求 | 応答 | 説明 |", "| --- | --- | --- |"]
        for n in names:
            doc = all_tables[n + "Request"]["doc"]
            m = re.match(r"->\s*([^.]+)\.?\s*(.*)", doc)
            reply, rest = (m.group(1).strip(), m.group(2).strip()) if m else ("", doc)
            out.append(f"| [`{n}`](#{n.lower()}) | {cell(reply)} | {cell(rest)} |")
        out.append("")
        for n in names:
            t = all_tables[n + "Request"]
            out += [f"### {n}", ""]
            if t["fields"]:
                out += ["| フィールド | 型 | 必須 | 説明 |", "| --- | --- | --- | --- |"]
                for f in t["fields"]:
                    out.append(f"| `{f['name']}` | `{cell(f['type'])}` | {'はい' if f['required'] else ''} | {cell(f['doc'])} |")
            else:
                out.append("フィールドはありません。")
            out.append("")

    out += ["## 通知", "", "`tsugumid` から接続しているクライアントへ送られます。", ""]
    for n in union_members(text, "NotificationPayload"):
        out.append(f"- `{n}`")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    made = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == made else 1)
    OUT.write_text(made)
