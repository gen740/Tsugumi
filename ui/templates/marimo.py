"""Source of the ordinary Python marimo Card scaffold shared by both clients."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]


def files():
    card = {'language': 'python', 'inputs': [{'name': 'data'}], 'filesystem': True, 'recordIO': True,
            'retainArtifact': True, 'artifactOutput': 'report', 'reuseWorker': False,
            'params': [{'name': name, 'type': kind, 'data': data} for name, kind, data in [
                ('notebook', 'string', 'notebook.py'),
                ('bindings', 'string', '{"source":"inputs.data.value","factor":"param.factor"}'),
                ('selected', 'string', 'result'), ('factor', 'double', 2)]]}
    return {
        '_card.json': json.dumps(card, indent=2) + '''
''',
        '_meta.json': json.dumps({'description': 'Run a marimo notebook once, emit a numeric result and retain a static HTML snapshot. Reactive editing is not a committed Run.'}, indent=2) + '''
''',
        '_outputs.fbs': '''attribute "tsugumi";
namespace notebook;
table Number { value:double; }
table Files { value:string; }
table Outputs { value:Number (required); report:Files (required, tsugumi: "directory"); }
root_type Outputs;
''',
        'default.nix': '''{ pkgs, inputs, params }:
let
  sdk = inputs.tsugumi.sdk { languages = [ "python" ]; };
in
{
  run = inputs.tsugumi.pythonCard {
    inherit sdk;
    src = ./src;
    packages = ps: [ ps.marimo ps.matplotlib ];
    fonts = [ pkgs.ipaexfont ];
  };
}
''',
        'src/main.py': '''"""Map inputs/params to notebook variables, then commit outputs once."""
import tsugumi
import json
import math
from pathlib import Path
from tsugumi import Failure
from tsugumi.notebook import bindings, run as run_notebook
import outputs.value.notebook.Number as number
import outputs.report.notebook.Files as files


def main(inputs, report, run):
    p = inputs.params
    selected = p.selected.decode()
    definitions = bindings(inputs, json.loads(p.bindings.decode()))
    values, folder = run_notebook(report, run, Path(__file__).parent, p.notebook.decode(), definitions, [selected])
    value = values[selected]
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise Failure("output_invalid", "The selected notebook result must be a finite number; edit the output schema/source for another type")
    b = tsugumi.builder()
    number.Start(b); number.AddValue(b, value)
    yield {"value": tsugumi.message(b, number.End(b))}
    b = tsugumi.builder(); path = b.CreateString(str(folder))
    files.Start(b); files.AddValue(b, path)
    yield {"report": tsugumi.message(b, files.End(b))}
''',
        'src/notebook.py': '''"""A normal marimo notebook; Tsugumi overrides the configuration cell."""
import marimo

app = marimo.App()


@app.cell
def configuration():
    source = 4.0
    factor = 2.0
    return source, factor


@app.cell
def calculation(source, factor):
    result = source * factor
    return result,


@app.cell
def explanation(result):
    import marimo as mo
    mo.md(f"## Notebook result\\n\\nThe selected result is **{result:g}**.")
    return mo,


@app.cell
def figure(source, result):
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots()
    ax.bar(["Input", "Result"], [source, result])
    ax.set_title("One committed notebook invocation")
    fig
    return fig, ax, plt


if __name__ == "__main__":
    app.run()
''',
    }


def outputs():
    data = json.dumps(files(), ensure_ascii=False, indent=2) + '''
'''
    swift = '''// Generated by ui/templates/marimo.py. Edit that source, not this file.
import Foundation

enum MarimoTemplate {
  static let files: [String: String] = try! JSONDecoder().decode([String: String].self, from: Data(json.utf8))
  private static let json = ####"""
''' + data + '''"""####
}
'''
    return {ROOT / 'ui/templates/marimo.json': data, ROOT / 'macOS/Sources/App/Model/MarimoTemplate.swift': swift}


if __name__ == '__main__':
    for path, value in outputs().items():
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f'{path} is stale')
        else:
            path.write_text(value)
