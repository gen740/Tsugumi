def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render() -> str:
    """The text of Localizable.strings: exactly this table, nothing else."""
    lines = ["/* Generated by macOS/Resources/tools/en_strings.py. */\n"]
    lines += [f"{quote(k)} = {quote(EN[k])};\n" for k in sorted(EN)]
    return "".join(lines)


def missing(directory: str) -> list[str]:
    keys = set()
    for path in glob.glob(os.path.join(directory, "*.stringsdata")):
        data = json.load(open(path, encoding="utf-8"))
        for table in data.get("tables", {}).values():
            keys.update(entry["key"] for entry in table)
    return sorted(k for k in keys if k not in EN and re.search(r"[\u3040-\u30ff\u4e00-\u9fff]", k))


def main() -> None:
    if sys.argv[1:2] == ["--check"]:
        keys = missing(sys.argv[2])
        for k in keys:
            print(k)
        sys.exit(1 if keys else 0)
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "en.lproj", "Localizable.strings")
    with open(out, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"{len(EN)} strings -> {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
