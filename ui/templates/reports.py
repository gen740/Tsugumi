"""Shared R Markdown and Quarto Card files. Run to regenerate both UI bundles."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]


def templates():
    result = {}
    for kind, extension in [('rmarkdown', 'Rmd'), ('quarto', 'qmd')]:
        files = {
            '_card.json': json.dumps({
                'language': 'r', 'inputs': [{'name': 'data'}], 'filesystem': True,
                'recordIO': True, 'retainArtifact': True, 'artifactOutput': 'report',
                'params': [{'name': 'title', 'type': 'string', 'data': 'Analysis report'}],
            }, indent=2) + '\n',
            '_meta.json': json.dumps({'description': 'Render an R report to saved HTML. Connect data, edit the report source and set params. PDF is not supported.'}) + '\n',
            '_outputs.fbs': 'attribute "tsugumi";\nnamespace report;\ntable Path { value:string; }\ntable Outputs { report:Path (required, tsugumi: "directory"); html:Path (required, tsugumi: "file"); }\nroot_type Outputs;\n',
            'default.nix': '''{ pkgs, inputs, params }:
{
  run = inputs.tsugumi.reportCard {
    src = ./src;
    entry = "report.@EXT@";
    packages = ps: [ ];
  };
}
'''.replace('@EXT@', extension),
            f'src/report.{extension}': '''---
params:
  tsugumi: null
---

```{r setup, include=FALSE}
knitr::opts_chunk$set(echo = FALSE)
data <- params$tsugumi$inputs$data
settings <- params$tsugumi$params
```

# `r settings$title`

The input and settings below belong to this saved invocation.

```{r input-table}
knitr::kable(as.data.frame(data))
```

```{r input-plot}
values <- unlist(data, use.names = FALSE)
if (is.numeric(values)) plot(values, type = "b", xlab = "Observation", ylab = "Value")
```

File and Directory input paths are available through
`params$tsugumi$paths$data`. Add R packages in `default.nix`.
''',
        }
        result[f'report_{kind}'] = files
    return result


def outputs():
    data = json.dumps(templates(), ensure_ascii=False, indent=2) + '\n'
    swift = '''// Generated by ui/templates/reports.py.
import Foundation

enum ReportTemplates {
  static let files = try! JSONDecoder().decode([String: [String: String]].self, from: Data(json.utf8))
  private static let json = ####"""
''' + data + '''"""####
}
'''
    return {ROOT / 'ui/templates/reports.json': data,
            ROOT / 'macOS/Sources/App/Model/ReportTemplates.swift': swift}


if __name__ == '__main__':
    for path, value in outputs().items():
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f'{path} is stale')
        else:
            path.write_text(value)
