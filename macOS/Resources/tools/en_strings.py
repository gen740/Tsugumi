# A format specifier: %@, %lld, %llu, %d, %%, optionally positional (%2$llu).
SPEC = re.compile(r"%(?:(\d+)\$)?(?:ll|l|h)?[@dDuUxXoOfeEgGcCsSpaA%]")


def specifiers(s: str) -> list[str]:
    """The arguments a format takes, in the order they are given."""
    found, order = [], 0
    for m in SPEC.finditer(s):
        if m.group(0).endswith("%"):
            continue
        spec = m.group(0)[1:] if m.group(1) is None else m.group(0)[len(m.group(1)) + 2:]
        index = int(m.group(1)) if m.group(1) else (order := order + 1)
        found.append((index, spec))
    return [spec for _, spec in sorted(found)]

