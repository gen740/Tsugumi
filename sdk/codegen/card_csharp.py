"""Generate typed C# object-API accessors from the resolved Card contract."""
import json
import re
from pathlib import Path
import sys


def qualified(name):
    return 'global::' + '.'.join('@' + part for part in name.split('.'))


def property_name(name):
    return '@' + name[:1].upper() + name[1:]


def catalog_property(name):
    return '@' + ''.join(part[:1].upper() + part[1:] for part in name.split('_'))


def generate(contract):
    lines = ['// Generated by the Tsugumi SDK. Do not edit.', '#nullable enable',
             'using Google.FlatBuffers;', 'namespace Tsugumi;',
             'public sealed class Inputs {',
             '  private readonly InvocationScope scope;',
             '  private readonly global::@inputs.@Inputs table;',
             '  internal Inputs(InvocationScope value) {',
             '    scope = value;',
             '    table = global::@inputs.@Inputs.GetRootAsInputs(value.InputBuffer);',
             '  }',
             '  public global::@params.@ParamsT Params => global::@params.@Params.GetRootAsParams(scope.Params).UnPack();',
             '  public bool HasInput(string port) => port switch {']
    for port in contract['inputs']:
        lines.append(f'    {json.dumps(port["name"])} => table.{catalog_property(port["name"])}.HasValue,')
    lines += ['    _ => false,', '  };', '  public PortKind InputKind(string port) => port switch {']
    kinds = {'file': 'File', 'directory': 'Directory', 'flatbuffer': 'FlatBuffer'}
    for port in contract['inputs']:
        lines.append(f'    {json.dumps(port["name"])} when HasInput(port) => PortKind.{kinds[port["kind"]]},')
    lines += ['    _ => throw new Failure("input_missing", $"Input {port} is absent"),', '  };']
    for port in contract['inputs']:
        prop = property_name(port['name'])
        field = catalog_property(port['name'])
        if port['required']:
            value = f'(table.{field} ?? throw new Failure("input_missing", "Input {port["name"]} is absent")).UnPack()'
        else:
            value = f'table.{field}?.UnPack()'
        lines.append(f'  public {qualified(port["type"])}T{"" if port["required"] else "?"} {prop} => {value};')
    lines += ['}', 'public sealed class Outputs {']
    for port in contract['outputs']:
        lines.append(f'  public {qualified(port["type"])}T? {property_name(port["name"])} {{ get; set; }}')
    lines += ['  internal byte[] Pack() {',
              '    var value = new global::@outputs.@OutputsT {']
    for port in contract['outputs']:
        prop = property_name(port['name'])
        lines.append(f'      {catalog_property(port["name"])} = {prop},')
    lines += ['    };', '    var builder = new FlatBufferBuilder(1024);',
              '    builder.Finish(global::@outputs.@Outputs.Pack(builder, value).Value);',
              '    return builder.SizedByteArray();', '  }']
    return '\n'.join(lines+['}', ''])


if __name__=='__main__':
    output = Path(sys.argv[2])
    # flatc leaves namespace identifiers unescaped, including Tsugumi's fixed
    # `params` namespace (a C# keyword). Verbatim identifiers preserve the schema.
    for generated in output.parent.rglob("*.cs"):
        text = generated.read_text()
        text = re.sub(r"(namespace |global::)([A-Za-z_][\w.]*)",
                      lambda match: match[1] + ".".join("@" + part for part in match[2].split(".")), text)
        generated.write_text(text)
    output.write_text(generate(json.loads(Path(sys.argv[1]).read_text())))
