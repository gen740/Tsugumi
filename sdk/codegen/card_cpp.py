"""Generates the C++ face of one Card from its contract (_contract.json):

  include/card.hh       Card::Input / Card::Output / Card::Params and run()
  src/card_adapter.cc   tsugumi_main: unpacks inputs, calls run(), packs outputs

    python3 card_cpp.py _contract.json <out dir>

Port types are the FlatBuffers object API types (flatc --gen-object-api) of the
generated _inputs / _outputs schemas; Cards never include those headers."""

import json
import os
import sys

KEYWORDS = set("""alignas alignof and asm auto bitand bitor bool break case catch char class compl concept const
consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double
dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new
noexcept not nullptr operator or private protected public register reinterpret_cast requires return short signed
sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid
typename union unsigned using virtual void volatile wchar_t while xor""".split())


def member(name):
    return name + "_" if name in KEYWORDS else name


def cxx(type_name):
    return "::" + "::".join(type_name.split("."))


def main(contract_path, out):
    c = json.load(open(contract_path))
    os.makedirs(os.path.join(out, "include"), exist_ok=True)
    os.makedirs(os.path.join(out, "src"), exist_ok=True)
    hh = ["// Generated by the Tsugumi SDK from this Card's contract. Do not edit.",
          "#pragma once", "", "#include <optional>", "", "#include <tsugumi/card_runtime.hh>", "",
          '#include "_inputs_generated.h"', '#include "_outputs_generated.h"', '#include "_params_generated.h"', "",
          "namespace Card {", "", "// Inputs of one invocation (optional ports may be absent).", "struct Input {"]
    for p in c["inputs"]:
        t = cxx(p["type"]) + "T"
        hh.append(f"  {t if p['required'] else 'std::optional<' + t + '>'} {member(p['name'])};"
                  + (f"  // {p['kind']}: .value is the path" if p["kind"] != "flatbuffer" else ""))
    hh += ["};", "", "// Outputs to send: set the ports this invocation produces.", "struct Output {"]
    for p in c["outputs"]:
        hh.append(f"  std::optional<{cxx(p['type'])}T> {member(p['name'])};"
                  + ("" if p["required"] else "  // optional")
                  + (f"  // {p['kind']}: .value is a path under tsugumi::context().output_directory" if p["kind"] != "flatbuffer" else ""))
    hh += ["};", "", "using Params = ::params::ParamsT;", "// This invocation's params.", "const Params& params();", "",
           "}  // namespace Card", "", "// Implemented by the Card.", "auto run(Card::Input& input) -> Card::Output;", "",
           "// Optional: called before the first invocation of each run. A worker with",
           "// reuseWorker stays across runs, so state kept in statics outlives a run;",
           "// define this to reset it.", "auto onRunStart() -> void;", ""]
    cc = ["// Generated by the Tsugumi SDK from this Card's contract. Do not edit.", '#include "card.hh"', "",
          "namespace {", "Card::Params g_params;", "}", "", "const Card::Params& Card::params() { return g_params; }", "",
          'extern "C" int tsugumi_main(const tsugumi_call* call) {',
          "  return tsugumi::card::invoke(call, [](tsugumi::card::Call& c) {",
          "    Card::Input input;"]
    for p in c["inputs"]:
        cc.append(f'    c.unpack<{cxx(p["type"])}>("{p["name"]}", input.{member(p["name"])});')
    cc += ["    g_params = Card::Params();", "    c.unpack_params<::params::Params>(g_params);",
           "    Card::Output output = run(input);"]
    for p in c["outputs"]:
        m = member(p["name"])
        cc.append(f'    if (output.{m}) c.emit_object<{cxx(p["type"])}>("{p["name"]}", *output.{m});')
    cc += ["  });", "}", "",
           "// The default when the Card does not define onRunStart.",
           "[[gnu::weak]] auto onRunStart() -> void {}", "",
           'extern "C" int tsugumi_run_start(const tsugumi_call* call) {',
           "  return tsugumi::card::invoke(call, [](tsugumi::card::Call&) { onRunStart(); });", "}", ""]
    open(os.path.join(out, "include", "card.hh"), "w").write("\n".join(hh))
    open(os.path.join(out, "src", "card_adapter.cc"), "w").write("\n".join(cc))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
