"""Writes docs/Protocol.md from the project, Agent and Host schemas: every request of
RequestPayload with its doc comment and fields, then the notifications. The
schema stays the single source; run this after changing it.
--check only compares."""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FBS = ROOT / "protocol" / "tsugumi.fbs"
OUT = ROOT / "docs" / "Protocol.md"

GROUPS = [
    ("Connection", ["SessionHello", "ProjectActivity", "CoreTrace"]),
    ("Projects and saving", ["ProjectOpen", "ProjectInspect", "ProjectHostRequirements", "CardId", "ProjectSave", "ProjectReload",
                       "ProjectValidate", "ProjectShell", "ProjectCacheClear", "ProjectCacheUsage", "RunScratchDelete", "OperationGet"]),
    ("Files", ["ProjectFileList", "ProjectFileStat", "ProjectFileRead"]),
    ("Nix evaluation and Card types", ["EvaluateNix", "NixPathLockSource", "CardNixPathNames", "InputTypes", "OutputTypes"]),
    ("Running", ["RunPlan", "Run", "RunCancel", "RunStatus"]),
    ("History and artifacts", ["RunHistory", "RunInvocations", "RunLatestInvocations", "RunRecord", "RunValueRead", "RunCategoryDelete", "RunFileReferences", "RunHistoryDelete",
                 "RunDefinitionPaths", "ArtifactList", "ArtifactRead", "LogRange", "RunEnvironments", "RunEnvironmentPaths", "RunEnvironmentUses"]),
    ("Views", ["ViewSetVisible", "ViewSave", "CardViewRead"]),
    ("Versions", ["VersionInit", "VersionMark", "VersionCheckout", "VersionGraph", "VersionCanvas", "VersionNote", "VersionDiff", "VersionComments"]),
]


def union_members(text: str, name: str) -> list[str]:
    found = re.search(rf"^union {name} \{{(.*?)^\}}", text, re.S | re.M)
    assert found, name
    body = re.sub(r"//[^\n]*", "", found.group(1))
    return [re.match(r"\s*(\w+)", member).group(1)
            for member in body.split(",") if member.strip()]


def tables(text: str) -> dict[str, dict]:
    """Each table with its /// comment and fields (name, type, required, comment)."""
    out: dict[str, dict] = {}
    comment: list[str] = []
    current = None
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("///"):
            comment.append(line[3:].strip())
            continue
        if current is None:
            one = re.match(r"table (\w+) \{(.*)\}\s*$", line)
            many = re.match(r"table (\w+) \{\s*$", line)
            if one:
                body = one.group(2).strip()
                out[one.group(1)] = {"doc": " ".join(comment), "fields": fields_of(body)}
            elif many:
                current = many.group(1)
                out[current] = {"doc": " ".join(comment), "fields": []}
            comment = []
        elif line == "}":
            current = None
            comment = []
        else:
            for f in fields_of(line):
                f["doc"] = " ".join(comment)
                out[current]["fields"].append(f)
            if line:
                comment = []
    return out


def fields_of(body: str) -> list[dict]:
    found = []
    for m in re.finditer(r"(\w+)\s*:\s*(\[?[\w.]+\]?)\s*(=\s*[^;(]+)?\s*(\([^)]*\))?\s*;", body):
        attrs = m.group(4) or ""
        found.append({"name": m.group(1), "type": m.group(2).replace("Tsugumi.Data.", ""),
                      "required": "required" in attrs, "doc": ""})
    return found


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    text = FBS.read_text()
    trace = tables((FBS.parent / "rpc_trace.fbs").read_text())
    all_tables = tables(text) | trace
    requests = [m[: -len("Request")] for m in union_members(text, "RequestPayload")]
    grouped = [n for _, names in GROUPS for n in names]
    assert sorted(grouped) == sorted(requests), set(grouped) ^ set(requests)

    out = [
        "# The RPC contract",
        "",
        "<!-- Generated by protocol/generate_docs.py from protocol/*.fbs: do not edit. -->",
        "",
        "The RPCs by which the UI, the Web and the Agent talk to `tsugumid`, generated from the doc comments of [protocol/tsugumi.fbs](../protocol/tsugumi.fbs).",
        "",
        "- **Format**: one message is one FlatBuffer (root `Tsugumi.RPC.Message`, file identifier `TSG1`). The WebSocket subprotocol is `tsugumi.rpc.v1`; on a Unix socket, a 4-byte length (little endian) is followed by the body.",
        "- **Failure**: any request may be answered with `Failure`.",
        "- **Requests that change something**: carry an `op_id`, and a resend with the same `op_id` is applied only once. If a response is lost, check with `OperationGet`.",
        "- **The Agent's tools**: made from the same schema (`tsugumi.bfbs`) ([Features](features.md#9-agent)).",
        "",
        "Layout proposals, layout schema validation and minimap placement belong to the host service ([protocol/host.fbs](../protocol/host.fbs)). Saving clients remove deleted Card references. The project core carries layout objects and opaque view JSON without interpreting presentation fields.",
        "",
        "A run belongs to one `tsugumid` process life. On restart, unfinished local and remote invocations become `failed/interrupted`; remote results are never rescued and nothing reruns automatically. The remote contract ([protocol/remote_worker.fbs](../protocol/remote_worker.fbs)) carries a fresh `core_life_id` on scoped requests. Regular status and log exchanges detect a lost connection; reconnection in the same core life resumes existing work. Startup only cancels/releases old jobs ([Remote execution](RemoteExecution.md)).",
        "",
        f"There are {len(requests)} requests.",
        "",
    ]
    for title, names in GROUPS:
        out += [f"## {title}", "", "| Request | Response | Description |", "| --- | --- | --- |"]
        for n in names:
            doc = all_tables[n + "Request"]["doc"]
            m = re.match(r"->\s*([^.]+)\.?\s*(.*)", doc)
            reply, rest = (m.group(1).strip(), m.group(2).strip()) if m else ("", doc)
            out.append(f"| [`{n}`](#{n.lower()}) | {cell(reply)} | {cell(rest)} |")
        out.append("")
        for n in names:
            t = all_tables[n + "Request"]
            out += [f"### {n}", ""]
            if t["fields"]:
                out += ["| Field | Type | Required | Description |", "| --- | --- | --- | --- |"]
                for f in t["fields"]:
                    out.append(f"| `{f['name']}` | `{cell(f['type'])}` | {'yes' if f['required'] else ''} | {cell(f['doc'])} |")
            else:
                out.append("No fields.")
            out.append("")

    out += ["## Notifications", "", "Sent from `tsugumid` to connected clients.", ""]
    for n in union_members(text, "NotificationPayload"):
        out.append(f"- `{n}`")
    out += ["", "### Run events", "", "The `value` inside a `RunEvent` has one of these types.", ""]
    for n in union_members(text, "RunEventValue"):
        out.append(f"- `{n}`")
    out += ["", "## Host and Agent service contracts", "",
            "Both services include [service_common.fbs](../protocol/service_common.fbs): Hello, Failure, Acknowledgement, ProviderSelection, Access, PermissionKind, Usage and TextResult have one definition. Secret ProviderInput belongs only to Host.", "",
            "Agent keeps conversations, turns, tools and conversation access prompts. Host keeps shared operations, including reference demos and version notes; model use does not decide the contract. External Agents read demos through ToolCall (demo_list/demo_read), not direct Host RPC.", ""]
    common = tables((ROOT / "protocol/service_common.fbs").read_text())
    for service, identifier, principals in [("agent", "TSA1", "user and external"), ("host", "TSH1", "user only")]:
        schema = (ROOT / f"protocol/{service}.fbs").read_text()
        definitions = all_tables | common | tables(schema)
        out += [f"### {service.title()} service", "",
                f"Separate listener: `{identifier}`, WebSocket subprotocol `tsugumi.{service}.v1`; authenticated principals: {principals}.", "",
                "| Request | Fields |", "| --- | --- |"]
        for name in union_members(schema, "RequestPayload"):
            fields = definitions[name]["fields"]
            signature = ", ".join(f"`{f['name']}: {f['type']}`" + (" (required)" if f["required"] else "") for f in fields)
            out.append(f"| `{name}` | {signature or 'None'} |")
        out += ["", "Reply variants: " + ", ".join(f"`{name}`" for name in union_members(schema, "ReplyPayload")) + ".", ""]
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    made = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == made else 1)
    OUT.write_text(made)
