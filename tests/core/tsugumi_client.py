from Tsugumi.RPC.Message import MessageT  # noqa: E402
from Tsugumi.RPC.Payload import Payload  # noqa: E402
from Tsugumi.RPC.ReplyPayload import ReplyPayload  # noqa: E402
from Tsugumi.RPC.RequestPayload import RequestPayload  # noqa: E402
from Tsugumi.RPC.Request import RequestT  # noqa: E402


FAILURE_NAMES = {v: k for k, v in vars(FailureKind).items() if not k.startswith("_")}
REPLY_NAMES = {v: k for k, v in vars(ReplyPayload).items() if not k.startswith("_")}


def new_id() -> str:
    return str(uuid.uuid4())


def path(*segments: str) -> CardPathT:
    p = CardPathT()
    p.segments = list(segments)
    return p


class RpcFailure(Exception):
    def __init__(self, failure: Any):
        self.failure = failure
        self.kind = FAILURE_NAMES.get(failure.kind, str(failure.kind))
        self.args_map = {kv.key.decode() if isinstance(kv.key, bytes) else kv.key:
                         kv.value.decode() if isinstance(kv.value, bytes) else kv.value
                         for kv in (failure.args or [])}
        diag = failure.diagnostic
        if isinstance(diag, bytes):
            diag = diag.decode()
        self.diagnostic = diag
        super().__init__(f"{self.kind}: {diag}")


def _request_class(name: str):
    module = __import__(f"Tsugumi.RPC.{name}", fromlist=[name])
    return getattr(module, f"{name}T")


def make(name: str, /, **fields: Any):
    """Builds a request object, e.g. make("ProjectSaveRequest", baseRev=1, ...)."""
    obj = _request_class(name)()
    for k, v in fields.items():
        if not hasattr(obj, k):
            raise AttributeError(f"{name} has no field {k}")
        setattr(obj, k, v)
    return obj


def encode_request(request_id: int, name: str, obj: Any) -> bytes:
    req = RequestT()
    req.valueType = getattr(RequestPayload, name)
    req.value = obj
    msg = MessageT()
    msg.requestId = request_id
    msg.payloadType = Payload.Request
    msg.payload = req
    b = flatbuffers.Builder(1024)
    b.Finish(msg.Pack(b), file_identifier=b"TSG1")
    return bytes(b.Output())


def decode_message(buf: bytes) -> MessageT:
    m = _Message.Message.GetRootAs(buf, 0)
    return MessageT.InitFromObj(m)


class Client:
    """Synchronous request/reply client with a background reader thread."""

    def __init__(self, unix: Optional[str] = None, ws: Optional[str] = None,
                 origin: Optional[str] = None, subprotocol: str = "tsugumi.rpc.v1"):
        self._ws = None
        self._sock = None
        if unix:
            self._sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            self._sock.connect(unix)
        elif ws:
            from websockets.sync.client import connect
            headers = {"Origin": origin} if origin else None
            self._ws = connect(ws, subprotocols=[subprotocol], additional_headers=headers,
                               max_size=16 << 20, compression=None, close_timeout=2)
        else:
            raise ValueError("unix or ws is required")
        self._next = 1
        self._lock = threading.Lock()
        self._send_lock = threading.Lock()
        self._cv = threading.Condition(self._lock)
        self._replies: dict[int, MessageT] = {}
        self.notifications: deque = deque()
        self.closed = False
        self.reader_error: Exception | None = None
        self._reader = threading.Thread(target=self._read_loop, daemon=True)
        self._reader.start()

    # -- transport ---------------------------------------------------------

    def _send_payload(self, payload: bytes, deadline: float) -> None:
        left = deadline - time.monotonic()
        if left <= 0 or not self._send_lock.acquire(timeout=left):
            raise TimeoutError("RPC send lock deadline exceeded")
        try:
            left = deadline - time.monotonic()
            if left <= 0:
                raise TimeoutError("RPC send deadline exceeded")
            expired = threading.Event()

            def abort_send():
                expired.set()
                self._close_socket()

            # Changing the socket timeout would also affect the reader. Closing
            # it interrupts both Unix sendall and WebSocket's blocking send.
            watchdog = threading.Timer(left, abort_send)
            watchdog.daemon = True
            watchdog.start()
            try:
                try:
                    if self._sock:
                        self._sock.sendall(struct.pack("<I", len(payload)) + payload)
                    else:
                        self._ws.send(payload)
                finally:
                    watchdog.cancel()
                    # Finish any racing callback before the next sender enters.
                    watchdog.join()
            except Exception as error:
                if expired.is_set():
                    raise TimeoutError("RPC send deadline exceeded") from error
                raise
            if expired.is_set():
                raise TimeoutError("RPC send deadline exceeded")
        finally:
            self._send_lock.release()

    def _close_socket(self) -> None:
        sock = self._sock if self._sock is not None else self._ws.socket
        try:
            sock.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        try:
            sock.close()
        except OSError:
            pass

    def _recv_frame(self) -> Optional[bytes]:
        if self._sock:
            head = b""
            while len(head) < 4:
                chunk = self._sock.recv(4 - len(head))
                if not chunk:
                    return None
                head += chunk
            (n,) = struct.unpack("<I", head)
            if not 0 < n <= 16 << 20:
                raise ValueError(f"invalid RPC frame size: {n}")
            body = bytearray()
            while len(body) < n:
                chunk = self._sock.recv(min(1 << 20, n - len(body)))
                if not chunk:
                    return None
                body += chunk
            return bytes(body)
        try:
            msg = self._ws.recv()
        except Exception:
            return None
        return msg if isinstance(msg, bytes) else None

    def _read_loop(self) -> None:
        try:
            while True:
                frame = self._recv_frame()
                if frame is None:
                    return
                msg = decode_message(frame)
                with self._cv:
                    if msg.payloadType == Payload.Reply:
                        self._replies[msg.requestId] = msg
                    else:
                        self.notifications.append(msg.payload)
                    self._cv.notify_all()
        except Exception as error:
            self.reader_error = error
        finally:
            with self._cv:
                self.closed = True
                self._cv.notify_all()

    def close(self) -> None:
        try:
            if self._sock:
                self._close_socket()
            else:
                self._ws.close()
        except OSError:
            pass
        if threading.current_thread() is not self._reader:
            self._reader.join(timeout=2)

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()

    # -- requests ------------------------------------------------------------

    def send(self, name: str, obj: Any, request_id: Optional[int] = None,
             timeout: float = 30.0) -> int:
        return self._send_request(name, obj, request_id, time.monotonic() + timeout)

    def _send_request(self, name: str, obj: Any, request_id: Optional[int], deadline: float) -> int:
        with self._lock:
            rid = request_id if request_id is not None else self._next
            self._next = max(self._next, rid) + 1
        self._send_payload(encode_request(rid, name, obj), deadline)
        return rid

    def wait_reply(self, rid: int, timeout: float = 30.0) -> Any:
        return self._wait_reply(rid, time.monotonic() + timeout)

    def _wait_reply(self, rid: int, deadline: float) -> Any:
        with self._cv:
            while rid not in self._replies:
                if self.closed:
                    raise ConnectionError(f"connection closed: {self.reader_error or 'EOF'}") from self.reader_error
                left = deadline - time.monotonic()
                if left <= 0:
                    raise TimeoutError(f"no reply to request {rid}")
                self._cv.wait(left)
            msg = self._replies.pop(rid)
        reply = msg.payload
        if reply.valueType == ReplyPayload.Failure:
            raise RpcFailure(reply.value)
        return reply.value

    def call(self, name: str, timeout: float = 30.0, **fields: Any) -> Any:
        deadline = time.monotonic() + timeout
        rid = self._send_request(name, make(name, **fields), None, deadline)
        return self._wait_reply(rid, deadline)

    def wait_notification(self, pred: Callable[[Any], bool], timeout: float = 30.0) -> Any:
        deadline = time.monotonic() + timeout
        with self._cv:
            while True:
                for i, n in enumerate(self.notifications):
                    if pred(n):
                        del self.notifications[i]
                        return n
                if self.closed:
                    raise ConnectionError(f"connection closed: {self.reader_error or 'EOF'}") from self.reader_error
                left = deadline - time.monotonic()
                if left <= 0:
                    raise TimeoutError("notification not received")
                self._cv.wait(left)

    # -- conveniences ------------------------------------------------------------

    def hello(self, token: Optional[str] = None, project: Optional[str] = None, language: Optional[str] = None):
        return self.call("SessionHelloRequest", protocol=1, clientId=new_id(), token=token,
                         expectedProjectId=project, language=language)

    def open(self, view_id: Optional[str] = None):
        return self.call("ProjectOpenRequest", viewId=view_id)


def change(kind: str, **fields: Any):
    """A DocumentChange of the given variant, e.g. change("SetProject", json=...)."""
    module = __import__(f"Tsugumi.RPC.{kind}", fromlist=[kind])
    inner = getattr(module, f"{kind}T")()
    for k, v in fields.items():
        setattr(inner, k, v)
    from Tsugumi.RPC.DocumentChange import DocumentChangeT  # noqa: WPS433
    from Tsugumi.RPC.DocumentChangeValue import DocumentChangeValue  # noqa: WPS433
    c = DocumentChangeT()
    c.valueType = getattr(DocumentChangeValue, kind)
    c.value = inner
    return c


def text(v: Any) -> Any:
    return v.decode() if isinstance(v, bytes) else v


def line_chart_series(value):
    """Decode a built-in line view's binary input for integration assertions."""
    import json
    import struct
    from types import SimpleNamespace
    assert text(value.module).endswith("-tsugumi-view-line-chart")
    config = json.loads(text(value.configJson))
    blobs = {text(b.name): bytes(b.data) for b in value.blobs}
    x = struct.unpack("<" + "d" * (len(blobs["x"]) // 8), blobs["x"])
    y = struct.unpack("<" + "d" * (len(blobs["y"]) // 8), blobs["y"])
    return [SimpleNamespace(id=s["id"], label=s["label"], x=x[s["offset"]:s["offset"] + s["count"]],
                            y=y[s["offset"]:s["offset"] + s["count"]]) for s in config["series"]]
