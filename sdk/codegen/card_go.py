"""Generate owned Go input/output objects and the Card's C entry points."""
import json
import os
import sys


def exported(name):
    return ''.join(part[:1].upper() + part[1:] for part in name.split('_'))


def main(contract_path, out):
    contract=json.load(open(contract_path))
    imports={'tsugumi/params':'params', 'tsugumi/inputs':'input_types', 'tsugumi/outputs':'output_types'}
    for i,port in enumerate(contract['inputs']+contract['outputs']):
        imports['tsugumi/'+port['type'].rsplit('.',1)[0].replace('.','/')]='port'+str(i)
    def typ(port):
        ns,name=port['type'].rsplit('.',1)
        return imports['tsugumi/'+ns.replace('.','/')]+'.'+name
    code=['// Code generated by Tsugumi. DO NOT EDIT.','package tsugumi','import (','"unsafe"','flatbuffers "tsugumi/flatbuffers"','host "tsugumi/internal/host"']
    code += [f'{alias} "{path}"' for path,alias in imports.items()]
    code += [')', 'type Report = host.Report', 'type Run = host.Run', 'type Failure = host.Failure',
             'var ErrClosed = host.ErrClosed', 'func Fail(kind, message string) error { return host.Fail(kind, message) }',
             'type Params = params.ParamsT','type Inputs struct {','params []byte', 'table *input_types.Inputs']
    code += ['}','type Output struct {']
    code += [f'{exported(p["name"])} *{typ(p)}T' for p in contract['outputs']]
    code += ['}']
    code += [f'type Output{exported(p["name"])} = {typ(p)}T' for p in contract['outputs']]
    code += ['func (inputs Inputs) Params() *Params { return params.GetRootAsParams(inputs.params,0).UnPack() }']
    for p in contract['inputs']:
        accessor = exported(p["name"])
        code += [f'func (inputs Inputs) {accessor}() *{typ(p)}T {{ if inputs.table==nil{{return nil}};value:=inputs.table.{accessor}(nil);if value==nil{{return nil}};return value.UnPack() }}']
    code += ['func readInput(scope *host.Scope) (Inputs,error) {','var inputs Inputs',
             'params,err:=scope.ParamsBytes();if err!=nil{return inputs,err}', 'inputs.params=params',
             'bytes,err:=scope.InputsBytes();if err!=nil{return inputs,err}',
             'inputs.table=input_types.GetRootAsInputs(bytes,0)']
    for p in contract['inputs']:
        if p['required']:
            code += [f'if inputs.table.{exported(p["name"])}(nil)==nil{{return inputs,Fail("input_missing",{json.dumps(p["name"])})}}']
    code += ['return inputs,nil','}','func (out Output) pack() []byte {',
             'builder:=flatbuffers.NewBuilder(256)', 'root:=(&output_types.OutputsT{']
    code += [f'{exported(p["name"])}: out.{exported(p["name"])},' for p in contract['outputs']]
    code += ['}).Pack(builder)', 'builder.Finish(root)', 'return builder.FinishedBytes()', '}', '''
func InvokeRun(raw unsafe.Pointer, function any) ([]byte, int) {
 var bytes []byte
 status := host.Invoke(raw,func(scope *host.Scope) error {
  inputs,err:=readInput(scope);if err!=nil{return err}
  report:=host.NewReport(scope)
  var out Output
  switch f:=function.(type) {
  case func(Inputs)(Output,error): out,err=f(inputs)
  case func(Inputs,*Report)(Output,error): out,err=f(inputs,report)
  case func(Inputs,*Report,*Run)(Output,error): out,err=f(inputs,report,host.NewRun(scope))
  default: return Fail("worker_failed","define run(inputs[, report[, run]])")
  }
  if err!=nil{return err}
  if err:=scope.Wait();err!=nil{return err}
  bytes=out.pack()
  return nil
 })
 return bytes,status
}
func InvokeStart(raw unsafe.Pointer, function any) int {
 return host.Invoke(raw,func(scope *host.Scope) error {
  inputs,err:=readInput(scope);if err!=nil{return err}
  switch f:=function.(type) {
  case func(Inputs) error: return f(inputs)
  case func(Inputs,*Report) error: return f(inputs,host.NewReport(scope))
  case func(Inputs,*Report,*Run) error: return f(inputs,host.NewReport(scope),host.NewRun(scope))
  default: return Fail("worker_failed","define onRunStart(inputs[, report[, run]])")
  }
 })
}
''']
    os.makedirs(out,exist_ok=True)
    open(os.path.join(out,'card.go'),'w').write('\n'.join(code))
    open(os.path.join(out,'adapter.go.in'),'w').write('''// Code generated by Tsugumi. DO NOT EDIT.
package main
/* #include "tsugumi/internal/host/abi.h" */
import "C"
import (
 "tsugumi"
 "unsafe"
)
//export tsugumi_card_invoke
func tsugumi_card_invoke(call *C.tsugumi_call, outputs *C.tsugumi_buffer) C.int {
 raw := unsafe.Pointer(call)
 switch call.phase {
 case C.TSUGUMI_PREPARE, C.TSUGUMI_LOAD:
  return 0
 case C.TSUGUMI_RUN_START:
  return C.int(tsugumi.InvokeStart(raw,onRunStart))
 case C.TSUGUMI_RUN:
  bytes, status := tsugumi.InvokeRun(raw,run)
  if status != 0 { return C.int(status) }
  outputs.data = (*C.uint8_t)(C.CBytes(bytes))
  outputs.size = C.size_t(len(bytes))
  return 0
 }
 return 1
}
func main() {}
''')


if __name__=='__main__':main(sys.argv[1],sys.argv[2])
