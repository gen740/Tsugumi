"""Tsugumi RPC client used by the integration tests.

Speaks generation 1 of the FlatBuffers contract over a Unix socket
(4 byte little-endian length + FlatBuffer) or WebSocket (/rpc,
subprotocol tsugumi.rpc.v1). Uses the bindings generated by flatc
(object API) from protocol/*.fbs into the build tree.
"""

from __future__ import annotations

import os
import socket
import struct
import sys
import threading
import time
import uuid
from collections import deque
from typing import Any, Callable, Optional

