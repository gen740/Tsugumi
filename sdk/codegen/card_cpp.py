"""Generates the C++ face of one Card from its contract (_contract.json):

  include/card.hh       Card::Inputs / Card::Output / Card::Params and run()
  src/card_adapter.cc   tsugumi_main: unpacks inputs, calls run(), packs outputs

    python3 card_cpp.py _contract.json <out dir>

Port types are the FlatBuffers object API types (flatc --gen-object-api) of the
generated _inputs / _outputs schemas; Cards never include those headers."""

import json
import os
import sys

KEYWORDS = set("""alignas alignof and asm auto bitand bitor bool break case catch char class compl concept const
consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double
dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new
noexcept not nullptr operator or private protected public register reinterpret_cast requires return short signed
sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid
typename union unsigned using virtual void volatile wchar_t while xor""".split())


def member(name):
    return name + "_" if name in KEYWORDS else name


def cxx(type_name):
    return "::" + "::".join(type_name.split("."))


def main(contract_path, out):
    c = json.load(open(contract_path))
    os.makedirs(os.path.join(out, "include"), exist_ok=True)
    os.makedirs(os.path.join(out, "src"), exist_ok=True)
    hh = ["// Generated by the Tsugumi SDK from this Card's contract. Do not edit.",
          "#pragma once", "", "#include <optional>", "", "#include <tsugumi/card_runtime.hh>", "",
          '#include "_inputs_generated.h"', '#include "_outputs_generated.h"', '#include "_params_generated.h"', "",
          "namespace Card {", "", "// Inputs of one invocation (optional ports may be absent).", "struct Inputs {"]
    for p in c["inputs"]:
        t = cxx(p["type"]) + "T"
        hh.append(f"  {t if p['required'] else 'std::optional<' + t + '>'} {member(p['name'])};"
                  + (f"  // {p['kind']}: .value is the path" if p["kind"] != "flatbuffer" else ""))
    hh += ["  ::params::ParamsT params;", "};", "", "// Outputs to send: set the ports this invocation produces.", "struct Output {"]
    for p in c["outputs"]:
        hh.append(f"  std::optional<{cxx(p['type'])}T> {member(p['name'])};"
                  + ("" if p["required"] else "  // optional")
                  + (f"  // {p['kind']}: .value is a path under run.output_directory" if p["kind"] != "flatbuffer" else ""))
    hh.append("};")
    for p in c["inputs"]:
        for u in p.get("unions", []):
            t, members = cxx(u["type"]), [member(m) for m in u["members"]]
            hh += ["", f"// Calls f with the member inputs.{member(p['name'])}.{member(u['field'])} holds,",
                   "// e.g. visit(u, [](const auto& v) { return v.value; }).",
                   "template <class F>", f"auto visit(const {t}Union& u, F&& f) {{", "  switch (u.type) {"]
            hh += [f"    case {t}::{m}: return f(*u.As{m}());" for m in members]
            hh += ["    default: break;", "  }",
                   f'  throw ::tsugumi::Failure("output_invalid", "{p["name"]}.{u["field"]} holds no member");', "}"]
    hh += ["", "using Params = ::params::ParamsT;", "", "}  // namespace Card", "",
           "// Implement one overload; omit trailing roles when unused."]
    signatures = ["const Card::Inputs& inputs", "const Card::Inputs& inputs, tsugumi::Report& report",
                  "const Card::Inputs& inputs, tsugumi::Report& report, const tsugumi::Run& run"]
    for function, result in [("run", "Card::Output"), ("onRunStart", "void")]:
        hh += [f"auto {function}({args}) -> {result};" for args in signatures]
    cc = ["// Generated by the Tsugumi SDK. Do not edit.", '#include "card.hh"',
          "#if defined(__APPLE__)", "#define TSUGUMI_OPTIONAL __attribute__((weak_import))",
          "#else", "#define TSUGUMI_OPTIONAL __attribute__((weak))", "#endif"]
    for function, result in [("run", "Card::Output"), ("onRunStart", "void")]:
        cc += [f"TSUGUMI_OPTIONAL auto {function}({args}) -> {result};" for args in signatures]
    cc += ["#undef TSUGUMI_OPTIONAL", "namespace {", "auto read(tsugumi::card::Call& c) -> Card::Inputs {", "  Card::Inputs inputs;"]
    for p in c["inputs"]:
        cc.append(f'  c.unpack<{cxx(p["type"])}>("{p["name"]}", inputs.{member(p["name"])});')
    cc += ["  c.unpack_params<::params::Params>(inputs.params);", "  return inputs;", "}", "}"]
    for entry, function, result in [("tsugumi_main", "run", "Card::Output"), ("tsugumi_run_start", "onRunStart", "void")]:
        cc += [f'extern "C" int {entry}(const tsugumi_call* call) {{',
               "  return tsugumi::card::invoke(call, [call](tsugumi::card::Call& c) {",
               "    const auto inputs = read(c);", "    tsugumi::Report report;"]
        if function == "run": cc += ["    Card::Output output;"]
        for i, args in enumerate(["const Card::Inputs&", "const Card::Inputs&, tsugumi::Report&", "const Card::Inputs&, tsugumi::Report&, const tsugumi::Run&"]):
            prefix = "if" if i == 0 else "else if"
            actual = ["inputs", "inputs, report", "inputs, report, tsugumi::Run(call)"][i]
            assign = "output = " if function == "run" else ""
            cc.append(f"    {prefix} (auto f = static_cast<{result}(*)({args})>({function})) {assign}f({actual});")
        if function == "run":
            cc += ['    else throw tsugumi::Failure("worker_failed", "define run(inputs[, report[, run]])");']
            for p in c["outputs"]:
                m = member(p["name"])
                cc.append(f'    if (output.{m}) c.emit_object<{cxx(p["type"])}>("{p["name"]}", *output.{m});')
        cc += ["  });", "}", ""]
    open(os.path.join(out, "include", "card.hh"), "w").write("\n".join(hh))
    open(os.path.join(out, "src", "card_adapter.cc"), "w").write("\n".join(cc))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
