"""Generate owned Go input/output objects and the Card's C entry points."""
import json
import os
import sys


def exported(name):
    return ''.join(part[:1].upper() + part[1:] for part in name.split('_'))


def main(contract_path, out):
    contract=json.load(open(contract_path))
    imports={'tsugumi/params':'params'}
    for i,port in enumerate(contract['inputs']+contract['outputs']):
        imports['tsugumi/'+port['type'].rsplit('.',1)[0].replace('.','/')]='port'+str(i)
    def typ(port):
        ns,name=port['type'].rsplit('.',1)
        return imports['tsugumi/'+ns.replace('.','/')]+'.'+name
    code=['// Code generated by Tsugumi. DO NOT EDIT.','package tsugumi','import (','"unsafe"','flatbuffers "tsugumi/flatbuffers"']
    code += [f'{alias} "{path}"' for path,alias in imports.items()]
    code += [')','type Params = params.ParamsT','type Inputs struct {','params []byte']
    code += [f'port{exported(p["name"])} []byte' for p in contract['inputs']]
    code += ['}','type Output struct {']
    code += [f'{exported(p["name"])} *{typ(p)}T' for p in contract['outputs']]
    code += ['}']
    code += [f'type Output{exported(p["name"])} = {typ(p)}T' for p in contract['outputs']]
    code += ['func (inputs Inputs) Params() *Params { return params.GetRootAsParams(inputs.params,0).UnPack() }']
    for p in contract['inputs']:
        package,name=typ(p).rsplit('.',1)
        code += [f'func (inputs Inputs) {exported(p["name"])}() *{typ(p)}T {{ if inputs.port{exported(p["name"])}==nil{{return nil}};return {package}.GetRootAs{name}(inputs.port{exported(p["name"])},0).UnPack() }}']
    code += ['func readInput(scope *callScope) (Inputs,error) {','var inputs Inputs', 'bytes,err:=scope.paramsBytes();if err!=nil{return inputs,err}', 'inputs.params=bytes']
    for p in contract['inputs']:
        code += ['{',f'bytes,err:=scope.inputBytes({json.dumps(p["name"])});if err!=nil{{return inputs,err}}']
        if p['required']:
            code += [f'if bytes==nil{{return inputs,Fail("input_missing",{json.dumps(p["name"])})}}']
        code += [f'inputs.port{exported(p["name"])}=bytes','}']
    code += ['return inputs,nil','}','func (out Output) emit(scope *callScope) error {']
    for p in contract['outputs']:
        code += [f'if out.{exported(p["name"])}!=nil{{', 'builder:=flatbuffers.NewBuilder(256)',
                 f'root:=out.{exported(p["name"])}.Pack(builder);builder.Finish(root)',
                 f'if err:=scope.emit({json.dumps(p["name"])},builder.FinishedBytes());err!=nil{{return err}}','}']
    if not contract['outputs']:
        code += ['_ = flatbuffers.SizeUOffsetT']
    code += ['return nil','}', '''
func InvokeRun(raw unsafe.Pointer, function any) int {
 return Invoke(raw,func(scope *callScope) error {
  inputs,err:=readInput(scope);if err!=nil{return err}
  report:=&Report{scope}
  var out Output
  switch f:=function.(type) {
  case func(Inputs)(Output,error): out,err=f(inputs)
  case func(Inputs,*Report)(Output,error): out,err=f(inputs,report)
  case func(Inputs,*Report,*Run)(Output,error): out,err=f(inputs,report,&Run{scope})
  default: return Fail("worker_failed","define run(inputs[, report[, run]])")
  }
  if err!=nil{return err}
  if err:=scope.wait();err!=nil{return err}
  return out.emit(scope)
 })
}
func InvokeStart(raw unsafe.Pointer, function any) int {
 return Invoke(raw,func(scope *callScope) error {
  inputs,err:=readInput(scope);if err!=nil{return err}
  switch f:=function.(type) {
  case func(Inputs) error: return f(inputs)
  case func(Inputs,*Report) error: return f(inputs,&Report{scope})
  case func(Inputs,*Report,*Run) error: return f(inputs,&Report{scope},&Run{scope})
  default: return Fail("worker_failed","define onRunStart(inputs[, report[, run]])")
  }
 })
}
''']
    os.makedirs(out,exist_ok=True)
    open(os.path.join(out,'card.go'),'w').write('\n'.join(code))
    open(os.path.join(out,'adapter.go.in'),'w').write('''// Code generated by Tsugumi. DO NOT EDIT.
package main
import "C"
import (
 "tsugumi"
 "unsafe"
)
//export tsugumi_main
func tsugumi_main(raw unsafe.Pointer) C.int { return C.int(tsugumi.InvokeRun(raw,run)) }
//export tsugumi_run_start
func tsugumi_run_start(raw unsafe.Pointer) C.int { return C.int(tsugumi.InvokeStart(raw,onRunStart)) }
func main() {}
''')


if __name__=='__main__':main(sys.argv[1],sys.argv[2])
