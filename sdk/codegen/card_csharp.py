"""Generate typed C# object-API accessors from the resolved Card contract."""
import json
import re
from pathlib import Path
import sys


def qualified(name):
    return 'global::' + '.'.join('@' + part for part in name.split('.'))


def property_name(name):
    return '@' + name[:1].upper() + name[1:]


def generate(contract):
    lines = ['// Generated by the Tsugumi SDK. Do not edit.', '#nullable enable',
             'using Google.FlatBuffers;', 'using System.Collections.Generic;', 'using System.Threading.Tasks;', 'namespace Tsugumi;',
             'public sealed class Inputs {', '  private readonly InvocationScope scope;',
             '  internal Inputs(InvocationScope value) => scope = value;',
             '  public bool HasInput(string port) => scope.HasInput(port);', '  public PortKind InputKind(string port) => scope.InputKind(port);',
             '  public ByteBuffer Input(string port) => scope.Input(port);',
             '  public global::@params.@ParamsT Params => global::@params.@Params.GetRootAsParams(scope.Params).UnPack();']
    for port in contract['inputs']:
        kind=qualified(port['type']);table=port['type'].split('.')[-1]
        value=f'{kind}.GetRootAs{table}(scope.Input({json.dumps(port["name"])})).UnPack()'
        optional=not port['required']
        if optional:value=f'scope.HasInput({json.dumps(port["name"])}) ? {value} : null'
        lines.append(f'  public {kind}T{"?" if optional else ""} {property_name(port["name"])} => {value};')
    lines += ['}', 'public sealed class Outputs : Dictionary<string, byte[]> {',
              '  private IAsyncEnumerable<Outputs>? batches;',
              '  public static Outputs Stream(IAsyncEnumerable<Outputs> values) => new Outputs { batches = values };']
    for port in contract['outputs']:
        lines.append(f'  public {qualified(port["type"])}T? {property_name(port["name"])} {{ get; set; }}')
    lines += ['  internal async ValueTask SendAsync(InvocationScope scope) {',
              '    foreach (var pair in this) scope.OutputBytes(pair.Key, pair.Value);']
    for port in contract['outputs']:
        kind=qualified(port['type']);prop=property_name(port['name'])
        lines += [f'    if ({prop} is not null) {{', '      var builder = new FlatBufferBuilder(1024);',
                  f'      var root = {kind}.Pack(builder, {prop});', '      builder.Finish(root.Value);',
                  f'      scope.Output({json.dumps(port["name"])}, builder);', '    }']
    lines += ['    if (batches is not null) await foreach (var batch in batches) await batch.SendAsync(scope);', '  }']
    return '\n'.join(lines+['}', ''])


if __name__=='__main__':
    output = Path(sys.argv[2])
    # flatc leaves namespace identifiers unescaped, including Tsugumi's fixed
    # `params` namespace (a C# keyword). Verbatim identifiers preserve the schema.
    for generated in output.parent.rglob("*.cs"):
        text = generated.read_text()
        text = re.sub(r"(namespace |global::)([A-Za-z_][\w.]*)",
                      lambda match: match[1] + ".".join("@" + part for part in match[2].split(".")), text)
        generated.write_text(text)
    version = re.search(r"#define TSUGUMI_ABI_VERSION (\d+)u", Path(sys.argv[3]).read_text())[1]
    (output.parent / "AbiVersion.cs").write_text(f"namespace Tsugumi; internal static class Abi {{ internal const uint Version = {version}; }}\n")
    output.write_text(generate(json.loads(Path(sys.argv[1]).read_text())))
