"""Generate the C# Card scaffold shared by the Mac and Web creation menus."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
FILES = {
    '_card.json': json.dumps({'language': 'csharp', 'inputs': [{'name': 'in'}],
                             'params': [{'name': 'message', 'type': 'string', 'data': 'Hello from C#'}]}, indent=2) + '\n',
    '_outputs.fbs': 'namespace card;\ntable Outputs {}\nroot_type Outputs;\n',
    'default.nix': '''{ pkgs, inputs, params }:
let
  sdk = inputs.tsugumi.sdk { languages = [ "csharp" ]; };
in
{
  run = inputs.tsugumi.csharpCard { inherit sdk; src = ./src; };
}
''',
    'src/Card.cs': '''using System.Threading.Tasks;
using Tsugumi;

public sealed class Card : ICard
{
    public ValueTask RunAsync(Context context)
    {
        context.DisplayText(context.Parameters.Message);
        return ValueTask.CompletedTask;
    }
}
''',
}

data = json.dumps(FILES, ensure_ascii=False, indent=2) + '\n'
swift = '''// Generated by ui/templates/csharp.py.
import Foundation

enum CSharpTemplate {
  static let files = try! JSONDecoder().decode([String: String].self, from: Data(json.utf8))
  private static let json = ####"""
''' + data + '''"""####
}
'''
for path, content in [(ROOT / 'ui/templates/csharp.json', data),
                      (ROOT / 'macOS/Sources/App/Model/CSharpTemplate.swift', swift)]:
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'{path} is stale')
    else:
        path.write_text(content)
