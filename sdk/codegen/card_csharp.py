"""Generate typed C# object-API accessors from the resolved Card contract."""
import json
import re
from pathlib import Path
import sys


def qualified(name):
    return 'global::' + '.'.join('@' + part for part in name.split('.'))


def property_name(name):
    return '@' + name[:1].upper() + name[1:]


def generate(contract):
    lines = ['// Generated by the Tsugumi SDK. Do not edit.', '#nullable enable',
             'using Google.FlatBuffers;', 'namespace Tsugumi;',
             'public sealed class Inputs {',
             '  private readonly InvocationScope scope;']
    for index, _ in enumerate(contract['inputs']):
        lines.append(f'  private readonly ByteBuffer? input{index};')
    lines += ['  internal Inputs(InvocationScope value) {', '    scope = value;']
    for index, port in enumerate(contract['inputs']):
        fallback = f' ?? throw new Failure("input_missing", "{port["name"]}")' if port['required'] else ''
        lines.append(f'    input{index} = value.Input("{port["name"]}"){fallback};')
    lines += ['  }',
              '  public global::parameters.ParamsT Params => global::parameters.Params.GetRootAsParams(scope.Params).UnPack();',
              '  public bool HasInput(string port) => port switch {']
    for index, port in enumerate(contract['inputs']):
        lines.append(f'    {json.dumps(port["name"])} => input{index} is not null,')
    lines += ['    _ => false,', '  };', '  public PortKind InputKind(string port) => port switch {']
    kinds = {'file': 'File', 'directory': 'Directory', 'flatbuffer': 'FlatBuffer'}
    for port in contract['inputs']:
        lines.append(f'    {json.dumps(port["name"])} when HasInput(port) => PortKind.{kinds[port["kind"]]},')
    lines += ['    _ => throw new Failure("input_missing", $"Input {port} is absent"),', '  };']
    for index, port in enumerate(contract['inputs']):
        prop = property_name(port['name'])
        type_name = qualified(port["type"])
        root = f'{type_name}.GetRootAs{port["type"].rsplit(".", 1)[1]}(input{index}!).UnPack()'
        value = root if port["required"] else f'input{index} is null ? null : {root}'
        lines.append(f'  public {type_name}T{"" if port["required"] else "?"} {prop} => {value};')
    lines += ['}', 'public sealed class Outputs {']
    for port in contract['outputs']:
        lines.append(f'  public {qualified(port["type"])}T? {property_name(port["name"])} {{ get; set; }}')
    lines += ['  internal void Send(InvocationScope scope) {']
    for port in contract['outputs']:
        prop = property_name(port['name'])
        lines += [f'    if ({prop} is {{ }} value_{port["name"]}) {{',
                  '      var builder = new FlatBufferBuilder(256);',
                  f'      builder.Finish({qualified(port["type"])}.Pack(builder, value_{port["name"]}).Value);',
                  f'      scope.Send("{port["name"]}", builder.SizedByteArray());',
                  '    }']
    lines += ['  }']
    return '\n'.join(lines+['}', ''])


if __name__=='__main__':
    output = Path(sys.argv[2])
    # flatc leaves namespace segments unescaped. Card port names can be C#
    # keywords, such as the output port `out`.
    for generated in output.parent.rglob("*.cs"):
        text = generated.read_text()
        text = re.sub(r"(namespace |global::)([A-Za-z_][\w.]*)",
                      lambda match: match[1] + ".".join("@" + part for part in match[2].split(".")), text)
        generated.write_text(text)
    output.write_text(generate(json.loads(Path(sys.argv[1]).read_text())))
