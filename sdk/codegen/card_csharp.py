"""Generate typed C# object-API accessors from the resolved Card contract."""
import json
import re
from pathlib import Path
import sys


def qualified(name):
    return 'global::' + '.'.join('@' + part for part in name.split('.'))


def property_name(name):
    return '@' + name[:1].upper() + name[1:]


def generate(contract):
    lines=['// Generated by the Tsugumi SDK. Do not edit.', '#nullable enable', 'using Google.FlatBuffers;', 'namespace Tsugumi;',
           'public sealed partial class Context {',
           '  public CardInputs Inputs => new(this);', '  public CardOutputs Outputs => new(this);',
           '  public global::@params.@ParamsT Parameters => global::@params.@Params.GetRootAsParams(Params).UnPack();', '}',
           'public sealed class CardInputs {', '  private readonly Context context;', '  internal CardInputs(Context value) => context = value;']
    for port in contract['inputs']:
        kind=qualified(port['type']);table=port['type'].split('.')[-1]
        value=f'{kind}.GetRootAs{table}(context.Input({json.dumps(port["name"])})).UnPack()'
        optional=not port['required']
        if optional:value=f'context.HasInput({json.dumps(port["name"])}) ? {value} : null'
        lines.append(f'  public {kind}T{"?" if optional else ""} {property_name(port["name"])} => {value};')
    lines += ['}', 'public sealed class CardOutputs {', '  private readonly Context context;', '  internal CardOutputs(Context value) => context = value;']
    for port in contract['outputs']:
        kind=qualified(port['type'])
        lines += [f'  public void {property_name(port["name"])}({kind}T value) {{',
                  '    var builder = new FlatBufferBuilder(1024);', f'    var root = {kind}.Pack(builder, value);',
                  '    builder.Finish(root.Value);', f'    context.Output({json.dumps(port["name"])}, builder);', '  }']
    return '\n'.join(lines+['}', ''])


if __name__=='__main__':
    output = Path(sys.argv[2])
    # flatc leaves namespace identifiers unescaped, including Tsugumi's fixed
    # `params` namespace (a C# keyword). Verbatim identifiers preserve the schema.
    for generated in output.parent.rglob("*.cs"):
        text = generated.read_text()
        text = re.sub(r"(namespace |global::)([A-Za-z_][\w.]*)",
                      lambda match: match[1] + ".".join("@" + part for part in match[2].split(".")), text)
        generated.write_text(text)
    version = re.search(r"#define TSUGUMI_ABI_VERSION (\d+)u", Path(sys.argv[3]).read_text())[1]
    (output.parent / "AbiVersion.cs").write_text(f"namespace Tsugumi; internal static class Abi {{ internal const uint Version = {version}; }}\n")
    output.write_text(generate(json.loads(Path(sys.argv[1]).read_text())))
