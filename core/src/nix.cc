constexpr const char* kSdkVersion = "1";

std::string find_in_path(const std::string& name) {
  const char* path = std::getenv("PATH");
  if (!path) return {};
  std::string p(path);
  size_t s = 0;
  while (s <= p.size()) {
    size_t e = p.find(':', s);
    std::string dir = p.substr(s, e == std::string::npos ? std::string::npos : e - s);
    if (!dir.empty()) {
      auto candidate = stdfs::path(dir) / name;
      if (::access(candidate.c_str(), X_OK) == 0) return candidate.string();
    }
    if (e == std::string::npos) break;
    s = e + 1;
  }
  return {};
}

std::string entry_nix() {
  return R"NIX(# Generated by tsugumid. Evaluated in restricted mode without IFD.
#
# inputs.upstream."<card path>" / inputs.local.<id> are the attribute sets
# (package, scripts, extra attributes, functions) of the code Cards that have
# always run before this one. They are imported lazily: only what is
# referenced is evaluated, and branches that may not run are never offered.
let
  pin = builtins.fromJSON (builtins.readFile <tsugumi-gen/nixpkgs.json>);
  nixpkgs = builtins.fetchTarball { url = pin.url; sha256 = pin.narHash; };
  pkgs = import nixpkgs { system = builtins.currentSystem; config = { }; overlays = [ ]; };
  find = name: builtins.findFile builtins.nixPath name;
  up = builtins.fromJSON (builtins.readFile <tsugumi-gen/upstream.json>);
  inputsFor = sdk: deps: {
    tsugumi = sdk;
    upstream = builtins.listToAttrs (map (d: { name = d.key; value = cards.${d.key}; }) deps);
    local = builtins.listToAttrs (map (d: { name = d.local; value = cards.${d.key}; })
      (builtins.filter (d: d.local != null) deps));
  };
  importCard = u:
    let
      gen = find "tsugumi-up-gen-${toString u.n}";
      sdk = import <tsugumi-sdk/nix> { inherit pkgs; generated = gen; };
    in
    import (find "tsugumi-up-def-${toString u.n}" + "/default.nix") {
      inherit pkgs;
      params = builtins.fromJSON (builtins.readFile (gen + "/params-nix.json"));
      inputs = inputsFor sdk u.deps;
    };
  cards = builtins.listToAttrs (map (u: { name = u.key; value = importCard u; }) up.cards);
  tsugumi = import <tsugumi-sdk/nix> { inherit pkgs; generated = <tsugumi-gen>; };
  params = builtins.fromJSON (builtins.readFile <tsugumi-gen/params-nix.json>);
  card = import <tsugumi-card/default.nix> { inherit pkgs params; inputs = inputsFor tsugumi up.deps; };
in
tsugumi.manifest card
)NIX";
}

// One reference entry of upstream.json: {"key": "<path>", "local": "<id>"|null}.
std::string dep_json(const CardPath& target, const CardPath& from) {
  auto key = schema::string_value(path_key(target));
  bool same_scope = target.size() == from.size() &&
                    std::equal(target.begin(), target.end() - 1, from.begin(), from.end() - 1);
  auto local = same_scope ? schema::string_value(target.back()) : schema::capture("null");
  return schema::object_text({{"key", &key}, {"local", &local}});
}

