// The interpreter the kernel runs ELF executables of a Linux system with
// (binfmt_misc: a static qemu-user in the shared VM, boot.binfmt.emulatedSystems
// on NixOS), or "" when none is registered. Matched by the ELF header the
// entry's magic names, whatever the entry is called.
std::string binfmt_interpreter(const std::string& system) {
  std::string machine = system == "x86_64-linux" ? "3e00" : system == "aarch64-linux" ? "b700" : "";
  const stdfs::path dir = "/proc/sys/fs/binfmt_misc";
  std::error_code ec;
  if (machine.empty() || !stdfs::is_directory(dir, ec)) return "";
  std::ifstream status(dir / "status");
  std::string state;
  if (!std::getline(status, state) || state != "enabled") return "";
  for (const auto& e : stdfs::directory_iterator(dir, ec)) {
    auto name = e.path().filename().string();
    if (name == "register" || name == "status") continue;
    std::ifstream f(e.path());
    std::string line, interpreter, magic;
    bool enabled = false;
    while (std::getline(f, line)) {
      if (line == "enabled") enabled = true;
      else if (line.starts_with("interpreter ")) interpreter = line.substr(12);
      else if (line.starts_with("magic ")) magic = line.substr(6);
    }
    // 7f 'E' 'L' 'F', 64-bit, little-endian, ..., e_machine at byte 18.
    if (enabled && !interpreter.empty() && magic.starts_with("7f454c4602") && magic.size() >= 40 &&
        magic.substr(36, 4) == machine)
      return interpreter;
  }
  return "";
}

// The evaluator's entry: a function of the nixpkgs package set (read once
// per pin and reused) and of the Card's folders.
std::string entry_nix() {
  return R"NIX(# Generated by tsugumid. Evaluated in restricted mode without IFD.
#
# inputs.<port> is the exports set of the guaranteed producer of that input.
# Exports are shared by all run implementations and imported lazily.
#
# inputs.sources.<name> contains the selected packages of a pinned flake the
# project opts in to through nixSources. Approved JSON customizations are applied
# in the source evaluator before these derivation references are reconstructed.
pkgs: { sdk, gen, upstream, card, remote ? false }:
let
  # upstream.json is read here only: it names folders of this evaluator, so it
  # is kept out of `gen`, which builds take in by content.
  up = builtins.fromJSON (builtins.readFile upstream);
  # What Tsugumi evaluated apart from this evaluator: built when a Card uses it.
  sourceReaders.flake = v: {
    inherit (v) ref rev narHash;
    packages = builtins.mapAttrs (_: p:
      let
        package = {
          override = _: throw "External package functions stay in their source evaluator. Set nixSources[].overrides.<package>.override in tsugumi.json (JSON arguments). packages already selects the target system.";
          overrideAttrs = _: throw "Set nixSources[].overrides.<package>.overrideAttrs in tsugumi.json (JSON attributes; a pinned fetch is { fetchurl = { url; sha256; }; }). Functions cannot cross the source evaluator boundary.";
          type = "derivation";
          inherit (p) name;
          outputName = p.output;
          outputs = [ p.output ];
          drvPath = builtins.appendContext p.drv { ${p.drv} = { allOutputs = true; }; };
          outPath = builtins.appendContext p.out { ${p.drv} = { outputs = [ p.output ]; }; };
          ${p.output} = package;
        };
      in package) v.packages;
  };
  sourcesOf = g: builtins.listToAttrs (map (s: {
    name = s.name;
    value = sourceReaders.${s.type} s.value;
  }) (builtins.fromJSON (builtins.readFile (g + "/sources.json"))));
  inputsFor = tsugumi: g: deps: builtins.listToAttrs (map (d: {
    name = d.name;
    value = cards.${d.key}.exports or { };
  }) deps) // {
    inherit tsugumi;
    sources = sourcesOf g;
  };
  importCard = u:
    let
      ugen = /. + u.gen;
      usdk = import (sdk + "/nix") { inherit pkgs; generated = ugen; };
    in
    import (/. + u.def + "/default.nix") {
      inherit pkgs;
      params = builtins.fromJSON (builtins.readFile (ugen + "/params-nix.json"));
      inputs = inputsFor usdk ugen u.deps;
    };
  cards = builtins.listToAttrs (map (u: { name = u.key; value = importCard u; }) up.cards);
  tsugumi = import (sdk + "/nix") { inherit pkgs; generated = gen; };
  params = builtins.fromJSON (builtins.readFile (gen + "/params-nix.json"));
  self = import (card + "/default.nix") { inherit pkgs params; inputs = inputsFor tsugumi gen up.deps; };
  run = self.run or (throw "a Card needs run");
  executionList = builtins.isList run;
in
{
  inherit executionList;
  implementationCount = if executionList then builtins.length run else 1;
  manifest = tsugumi.manifestFor remote self;
}
)NIX";
}

// A Nix string literal.
std::string nix_quote(const std::string& s) {
  std::string q = "\"";
  for (char c : s) {
    if (c == '"' || c == '\\' || c == '$') q += '\\';
    q += c;
  }
  return q + "\"";
}

// File name of a project GC root: the Card (readable, plus a hash against
// collisions) and the result.
std::string root_prefix(const CardPath& card) {
  std::string k = path_key(card);
  std::string out;
  for (char c : k) out += std::isalnum(static_cast<unsigned char>(c)) || c == '-' || c == '_' ? c : '_';
  return out + "-" + crypto::sha256_hex(k).substr(0, 8) + "--";
}

auto dep_json(const CardPath& target, const std::string& name) -> std::string {
  auto key = schema::string_value(path_key(target));
  auto port = schema::string_value(name);
  return schema::object_text({{"key", &key}, {"name", &port}});
}

