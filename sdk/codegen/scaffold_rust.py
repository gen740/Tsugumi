"""Keep the native and Web Rust scaffolds identical, including Cargo.lock."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / 'sdk/rust/template'


def generate(check=False):
    files = {str(p.relative_to(TEMPLATE)): p.read_text() for p in sorted(TEMPLATE.rglob('*')) if p.is_file()}
    header = '// Generated by sdk/codegen/scaffold_rust.py. Do not edit.\n'
    outputs = {
        ROOT / 'web/src/model/rust-scaffold.ts': header + 'export const RUST_SCAFFOLD: Record<string, string> = ' + json.dumps(files, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'macOS/Sources/App/Model/RustScaffold.swift': header + 'enum RustScaffold {\n  static let files: [String: String] = [\n' + ''.join('    ' + json.dumps(k) + ': #"""\n' + v + '\n"""#,\n' for k, v in files.items()) + '  ]\n}\n',
    }
    for path, value in outputs.items():
        if check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f'Stale scaffold: {path}')
        else:
            path.write_text(value)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
