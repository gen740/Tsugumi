#include "tsugumi/document/input_schema.hh"

#include <algorithm>
#include <string_view>

#include "tsugumi/document/collect_type.hh"
#include "tsugumi/document/graph.hh"
#include "tsugumi/document/schema_id.hh"

namespace tsugumi {
namespace {

constexpr std::string_view kCollectedName = "tsugumi.builtin.Collected";
constexpr const char* kCollectedInclude = "include \"tsugumi/artifact.fbs\";\n";
constexpr std::string_view kArtifactName = "tsugumi.Artifact";

auto add_candidates(const Resolution& graph, size_t source,
                    const std::string& port,
                    std::map<std::string, types::TypeRef>& result) -> void {
  const auto& producer = graph.nodes[source];
  if (producer.kind == CardType::Merge) {
    auto candidates = graph.merge_candidates(source, port);
    result.merge(candidates);
    return;
  }
  if (const auto* output = producer.output(port); output && output->type)
    result.try_emplace(schema_id(*output->type), output->type);
}

}  // namespace

auto generated_input_schema(const Resolution& graph, const Node& node)
    -> std::string {
  const auto dest = graph.index.at(path_key(node.path));
  types::InputDeclarations declarations;
  std::string unions;
  std::string fields;
  bool uses_collected = false;
  int field_id = 0;
  for (const auto& port : node.inputs) {
    const auto wire = std::ranges::find_if(graph.edges, [&](const Edge& edge) {
      return edge.to == dest && edge.to_port == port.name;
    });
    if (wire == graph.edges.end()) continue;
    const auto letter = [](char c) {
      return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_';
    };
    if (port.name.empty() || !letter(port.name.front()) ||
        !std::ranges::all_of(port.name, [&](char c) {
          return letter(c) || (c >= '0' && c <= '9');
        })) {
      throw std::runtime_error("input port is not a FlatBuffers identifier: " +
                               port.name);
    }

    std::map<std::string, types::TypeRef> candidates;
    const auto& producer = graph.nodes[wire->from];
    const bool collect = producer.kind == CardType::Collect;
    if (collect) {
      for (const auto& member : graph.edges) {
        if (member.to != wire->from) continue;
        add_candidates(graph, member.from, member.from_port, candidates);
      }
    } else {
      add_candidates(graph, wire->from, wire->from_port, candidates);
    }
    const bool multiple_merge_candidates =
        (collect || producer.kind == CardType::Merge) && candidates.size() > 1;

    std::vector<std::string> names;
    for (const auto& [id, type] : candidates) {
      if (type->root_type == kCollectedName) {
        uses_collected = true;
        names.emplace_back(kCollectedName);
      } else {
        auto prefix = "inputs." + port.name;
        if (multiple_merge_candidates) prefix += ".s" + id.substr(0, 12);
        names.push_back(
            types::render_input_candidate(*type, prefix, id, declarations));
      }
    }
    std::string field_type;
    std::string field_schema;
    if (collect) {
      const auto* output = producer.output(wire->from_port);
      if (!output || !output->type) continue;
      uses_collected = true;
      field_type = kCollectedName;
      field_schema = schema_id(*output->type);
    } else if (names.size() == 1) {
      field_type = names.front();
      if (field_type == kArtifactName || field_type == kCollectedName)
        field_schema = candidates.begin()->first;
    } else if (names.size() > 1) {
      field_type = port.name + "_candidates";
      unions += "union " + field_type + " { ";
      for (size_t i = 0; i < names.size(); ++i)
        unions += (i ? ", " : "") + names[i];
      unions += " }\n";
      ++field_id;  // The discriminator takes its own id.
    } else {
      continue;
    }
    fields += "  " + port.name + ": " + field_type +
              " (id: " + std::to_string(field_id++);
    if (!field_schema.empty())
      fields += ", tsugumi_schema: \"" + field_schema + "\"";
    fields += ");\n";
  }
  std::string text =
      "// Generated by Tsugumi from the wiring and the upstream _outputs.fbs. "
      "Do not edit.\n";
  if (uses_collected || declarations.artifact) text += kCollectedInclude;
  text += "attribute \"tsugumi_schema\";\n";
  for (const auto& attr : declarations.attributes)
    text += "attribute \"" + attr + "\";\n";
  if (uses_collected) text += collect_schema_declarations();
  for (const auto& name : declarations.order)
    text += declarations.types.at(name);
  text += "namespace inputs;\n" + unions + "table Inputs {\n" + fields +
          "}\nroot_type Inputs;\n";
  return text;
}

}  // namespace tsugumi
